				<h2>Literature in a Digital Context</h2>

				<p>
					Understanding the broader context in which a phenomenon emerges is essential to
					grasping its most defining contours, especially in the case of digital literary
					media. To neglect this condition leads to what James O’Sullivan terms “myopia”: a
					form of critical segregation in which practices are severed from the contexts that
					shaped them (O’Sullivan, 2019, 1). This consideration is particularly important in
					the history of media, where new forms do not emerge in isolation, but in profound
					entanglement with their predecessors.
				</p>

				<p>
					The relationship between emergent and established media is so intimate that some
					scholars have argued that we must “recognise the fallacy of new media,”
					understanding the appearance of new forms as merely another phase within an ongoing
					cultural cycle (O’Sullivan, 2019, 4).
				</p>

				<p>
					Yet tracing these relations demands a more careful approach. To place a medium
					within its historical frame only partially reveals its nature, particularly when it
					is measured against prior forms. One must examine how the broader digital
					environment informs the singular characteristics of electronic literature. As
					O’Sullivan suggests: “To define e-lit as a mere juxtaposition of the old and the
					new is a gross oversimplification. How can we conceive of the product of this
					connection without understanding either ‘the old’ or ‘the new’ in themselves?”
					(O’Sullivan, 2019, 26).
				</p>

				<p>
					What, then, is the connection between the rise of written literature and the
					emergence of digital literature? Before answering, it is worth noting that this
					connection is, first and foremost, an analytical construction shaped by the scope
					and concerns of this investigation. Philosophically speaking, it is an epistemic
					connection—concerned with how we know and understand—rather than an ontological
					one, concerned with being itself.
				</p>

				<p>
					The transition into written and digital formats may be understood as part of the
					same cycle of media transformation. Both follow comparable patterns: each marks a
					substantial alteration of form that decisively affects the primary functions of
					media, namely the production, preservation, and dissemination of culture.
				</p>

				<p>
					After the invention of writing, oral narratives migrated fully into written form. A
					similar displacement is now taking place in the transition from physical supports to
					digital environments. This transformation has generated profound aesthetic and
					ethical consequences. The fundamental concepts developed throughout literary
					tradition serve here as a bridge for understanding the movement between traditional
					and digital literature.
				</p>

				<p>
					From a broader perspective, writing enabled both the proliferation and the
					segmentation of knowledge. What was once held within oral narrative gradually
					diversified into emerging disciplines such as philosophy and science. The digital
					era, however, has not only produced new disciplines—such as the digital
					humanities—but has also reopened the possibility of reintegration and collaboration
					across previously separated fields.
				</p>

				<p>
					What distinguishes the digital present is precisely its capacity to rebuild
					bridges between sciences and humanities, enabling new forms of collaboration,
					preservation, and circulation of knowledge. This is perhaps one of the most
					significant consequences of the digital context.
				</p>

				<p>
					Yet the history of media shows that every advance comes at a cost. The most
					immediate price of every revolution is the confusion it introduces: new territories
					demand exploration, but they also unsettle the understanding of what we thought we
					already knew. Just as the invention of writing compelled Aristotle to undertake the
					first major aesthetic reflection on literature, the arrival of digital formats now
					demands a renewed critical examination of literary form, its limits, and its
					consequences.
				</p>

                <h2>Aesthetics of Digital Literature</h2>

<h3>Aesthetic Features of Digital Literature</h3>

<p>
	Confined to books, literature was long constrained by linear text as the primary narrative
	structure, with this linearity shaping plot development. Consequently, the aesthetic
	experience was conditioned solely by the act of reading. Written literature stripped away
	much of the multimodality present in early epic narratives, where music and the poet's voice
	added other sensory dimensions, albeit in a rudimentary form. However, the invention of the
	web in the late 1990s initiated a profound transformation. The emergence of hypertext and
	integrating text and various media revived multimodality in literature. This fusion enriches
	storytelling, offering new ways to craft narratives and creating more profound layers of
	engagement and interaction. Just as the advent of writing gave rise to written literature,
	innovations introduced by the web and digital technologies have paved the way for a new
	literary domain: electronic literature.
</p>

<p>
	Electronic literature is a term of art that refers explicitly to digital-born genres, not
	traditional works merely displayed on electronic devices. This form of literature relies on
	computers not just for distribution but for its very creation. The first digital-born genre
	was hypertext fiction, which emerged in the 1980s (Hayles, 2008, 13-14). Hypertext fiction
	consists of non-linear stories where hyperlinked text allows readers to navigate different
	paths through the narrative, leading to multiple outcomes based on their choices. Notable
	examples include <em>Afternoon</em>, a novel by Michael Joyce and <em>Patchwork Girl</em> by
	Shelley Jackson.
</p>

<p>
	Later technological advances further enriched multimodality, allowing electronic literature
	to integrate text with visual and auditory elements seamlessly. This blending of media—
	through images, sounds, and animations—enhances the narrative, drawing readers deeper into
	the story. In combining visuals and text, illustrations, photographs, and videos offer
	context, evoke emotions, and elevate storytelling. For instance, Shelley Jackson's
	<em>Patchwork Girl</em> intertwines images and text non-linearly, creating a fragmented yet
	cohesive narrative that readers actively piece together.
</p>

<p>
	Auditory elements, such as background music, sound effects, and voiceovers, add another
	dimension to the reading experience. These audio components shape mood and guide
	interpretation, as seen in Donna Leishman's <em>Deviant: The Possession of Christian Shaw</em>,
	where a haunting soundtrack amplifies the eerie atmosphere. Additionally, animations can
	breathe life into the narrative, illustrating actions and abstract concepts or adding
	dynamism. Leishman’s <em>RedRidingHood</em> is a prime example, where interactive animations
	respond to reader choices, blending traditional storytelling with animated visuals to create
	a more engaging and immersive experience.
</p>

<p>
	In addition to reshaping linearity and multimodality, electronic literature introduced
	another significant innovation: interactivity. This advancement allowed readers to actively
	participate in the narrative, generating inputs that directly influenced the story's
	direction. The rise of Interactive Fiction in the 1980s, also known as text adventure games,
	exemplifies this shift. Readers no longer passively consumed stories but engaged with them by
	inputting commands to control characters and alter plot outcomes, resulting in diverse paths
	and multiple endings. Classic examples like Infocom's <em>Zork</em> and Steve Meretzky's
	<em>A Mind Forever Voyaging</em> showcase how interactive elements—such as clickable links,
	maps, and multimedia—transformed reading into a dynamic, participatory experience.
</p>

<p>
	Innovations were not confined to narrative genres but extended to poetry, leading to the
	emergence of Digital Poetry in the 1990s. Poets began to explore digital media, integrating
	text, images, sound, animation, and interactivity to expand the boundaries of traditional
	forms (Hayles, 2008, 53). This integration of multimedia elements enabled poets to create
	works that challenge and enrich conventional poetic expression.
</p>

<p>
	Another genre that emerged in the 1990s is flash fiction. Utilising Adobe Flash (formerly
	Macromedia Flash), this form of electronic literature creates multimedia stories that blend
	text, images, sound, and interactivity. Notable examples include <em>RedRidingHood</em> by
	Donna Leishman and <em>The Dazzle as Question</em> by Young-Hae Chang Heavy Industries.
</p>

<p>
	Improvements in internet accessibility and bandwidth in the late 1990s and early 2000s paved
	the way for the emergence of Network Fiction. This genre leverages the internet as a medium
	for storytelling, incorporating elements such as collaborative writing, reader participation,
	and real-time influences. Notable examples include <em>Lexia to Perplexia</em> by Talan
	Memmott and <em>Dakota</em> by Young-Hae Chang Heavy Industries.
</p>

<p>
	Efforts to integrate digital features into theatre led to the development of Interactive
	Drama in the early 2000s. This genre merges theatre, film, and gaming elements to create
	immersive, narrative-driven experiences. Participants engage with characters and influence
	the progression of the story. Notable examples include <em>Façade</em> by Michael Mateas and
	Andrew Stern and <em>The Last Express</em> by Jordan Mechner.
</p>

<p>
	The digital revolution in electronic literature encompasses changes in the form of works,
	including non-linearity, multimodality, and active reader engagement, and it also challenges
	traditional notions of authorship. Within this context, interdisciplinary and collaborative
	efforts have led to the emergence of new genres, such as Collaborative and Collective
	Narratives. Digital platforms have facilitated collaborative storytelling, allowing multiple
	authors or even readers to contribute to narrative development. Online writing communities and
	platforms like <em>Twine</em> exemplify this trend, enabling users to create and share
	interactive stories that others can expand and modify. This collaborative approach dissolves
	traditional boundaries between authors and readers, fostering a more democratic and inclusive
	storytelling process. By integrating diverse voices and perspectives, collaborative narratives
	enrich the storytelling experience and enhance its diversity.
</p>

<p>
	In the new millennium, the rapid evolution of media forms has accelerated, with emerging
	technologies like Augmented Reality (AR) and Virtual Reality (VR) potentially ushering in new
	realms of literature. Although it is too early to assess the impact of these technologies
	fully, they have already begun to give rise to innovative genres.
</p>

<p>
	Augmented Reality (AR) literature, emerging in the 2010s, utilises AR technology to overlay
	digital content onto the real world, creating interactive and immersive storytelling
	experiences. Notable examples include <em>Miranda</em> by Will Self, an AR-enhanced novel,
	and <em>The Ghosts of the Past</em> by ARTE.
</p>

<p>
	Virtual Reality (VR) literature from the 2010s offers fully interactive and
	three-dimensional narrative environments through VR technology, enabling readers to experience
	stories from within. Examples of this genre are <em>Wolves in the Walls</em> by Fable Studio
	and <em>The Key</em> by Celine Tricart.
</p>

<p>
	Transmedia storytelling, another genre from the 2010s, extends narratives across multiple
	platforms and media. This approach allows stories to be experienced through various devices
	and formats, such as books, websites, games, and social media. Examples include
	<em>The 39 Clues</em> series and <em>Inanimate Alice</em> by Kate Pullinger and Chris Joseph.
</p>

<p>
	Among the emerging technologies, artificial intelligence stands out, leading to the
	development of AI-driven literature in the 2020s. This genre harnesses AI to generate and
	adapt narratives in real time, providing personalised storytelling experiences tailored to
	individual reader interactions and inputs. Notable examples of AI-driven literature include
	<em>AI Dungeon</em> by Nick Walton and <em>Project December</em> by Jason Rohrer.
</p>

<p>
	These genres illustrate the evolution of electronic literature from simple hypertext fiction
	to complex, immersive experiences that integrate diverse forms of media and technology. Each
	genre expands the boundaries of traditional storytelling, providing novel ways for readers to
	interact with and shape the narrative.
</p>
			
