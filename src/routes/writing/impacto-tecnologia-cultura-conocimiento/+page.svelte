				<h2>Introduction</h2>

				<p>
					As implied by its title, this course extensively explores the influence of
					technology on human culture. To establish a foundation, an initial examination of
					the concept of human culture is presented. Subsequently, the focus narrows to
					scrutinize the methods through which this culture is transmitted, essentially
					delving into the history of media. The narrative unfolds through three key epochs in
					this history—Aural Tradition, Written Tradition, and, finally, the Digital Age.
				</p>

				<p>
					It's essential to highlight that this article is a compilation of comments generated
					during discussions conducted throughout the course. Consequently, the structure of
					the article is crafted with the specific intention of providing coherence to these
					diverse yet interconnected themes.
				</p>

				<h2>On the Impact of Digital Technology on the Culture of Knowledge</h2>

				<p>
					Digital technology is exerting a significant impact on all aspects of culture, and
					its emergence might represent the greatest progress ever seen in the field of human
					knowledge. What is the relevant task accomplished by digital technologies that
					supports this progress? To answer that question, we should travel back to the very
					early stages of human society.
				</p>

				<h3>The Origins of Culture</h3>

				<p>
					In ancient times, young Homo sapiens surpassed their predecessors—Homo erectus and
					Homo habilis—for a new dimension of their minds emerged, reshaping the course of the
					species. At an indistinct point in history, Sapiens began utilizing their minds not
					merely as tools for survival but also as gateways to a new spiritual realm.
				</p>

				<p>
					In the shadow of uncertainty, Homo sapiens grappled with the cruel mysteries of
					life, where the consciousness of death tinged their existence with a melancholy of
					gray grief and somber pain. Navigating the harshness of life with meager resources
					like raw meat and impure water, they faced a desolate reality. Unbeknownst to them,
					perhaps, a glimmer of divine intervention lingered on the horizon, as their minds
					would be endowed with the power to infuse meaning into their arduous lives and
					unravel the enigmas that cloaked the world in perpetual mystery.
				</p>

				<p>
					Subsequently, a flourishing imagination unfolded within their minds, breathing life
					into their surroundings with a myriad of creatures and creators. Gods observed their
					journey, governing the entire world. Creation myths unfolded, elucidating how these
					gods crafted and ruled, accompanied by dances, sacred objects, and intricate rituals
					that served to explain worldly phenomena and kindle a spark of hope, as they sought
					divine assistance.
				</p>

				<p>
					Ultimately, these transformative shifts marked the birth of religion, collective
					literary imagery, and the new spiritual realm encompassing the entirety of what we
					now recognize as culture. This powerful achievement is what deemed them worthy of
					the name they hold: Homo Sapiens—the humans who know.
				</p>

				<h3>Conservation of Culture</h3>

				<p>
					The emergence of a cultural sphere in human society undeniably marked the institution
					of a new era. Culture became the cohesive force binding the entirety of human
					existence, furnishing it with meaning, identity, moral codes, abstract knowledge,
					among others. It bestowed upon them the belief that the greatest danger they faced,
					the glacial shadow that perennially loomed over individuals, introducing existence
					to an everlasting darkness, could be overcome.
				</p>

				<p>
					Yet, death couldn't be defeated; it ceased to symbolize a definitive end; instead,
					it marked a passage to an immortal life. These communities knew they possessed an
					invaluable resource to navigate the path of life. Preserving and passing down this
					treasure to future generations was key to keep the species alive.
				</p>

				<h3>Transmission Media</h3>

				<p>
					Another crucial aspect of preservation is ensuring the right transmission so that
					culture remains alive despite generational changes.
				</p>

				<p>
					As the human population expanded, traditions multiplied, and the volume of
					information surpassed the capacity of collective memory. The challenges shifted to
					the nuances of the contents to be transmitted. Due to their reliance on human
					memory, myriad variations of the same traditions proliferated, leading to great
					disagreements that could even conclude in wars.
				</p>

				<p>
					Therefore, more effective means of transmission became necessary, leading to the
					development of media capable of surpassing the limitations of mortal memory. The
					development of culture became a product of this interplay between the evolution of
					media and the content transmitted.
				</p>

                <h2>The Written Era</h2>

<p>
	After the oral tradition, the next great milestone in the preservation and transmission of
	culture was the invention of writing. This marked a decisive turning point in human history
	and inaugurated a new era. Soon after its emergence, most cultures that gained access to this
	new textual technology transferred into writing the contents that had previously belonged to
	the oral sphere, giving rise to the first textual editions in history.
</p>

<p>
	Although writing allowed for the storage of incomparably greater amounts of information than
	human memory, new challenges emerged concerning the preservation of both content and form. On
	the one hand, the fragility of materials posed a constant threat, as texts were vulnerable to
	deterioration due to the limited durability of their supports. At the same time, primitive
	manuscript reproduction techniques were laborious and imprecise, producing a proliferation of
	textual variants with every new act of copying.
</p>

<p>
	Efforts to combat textual corruption led to significant advances in the development of more
	durable materials. The evolution of writing supports—from stone to clay tablets and animal
	skins—culminated in the decisive invention of paper. Around the fourth century before Christ,
	a notable shift also occurred with the adoption of parchment and the introduction of the
	codex format. Unlike the papyrus scroll, the codex offered a linear structure more conducive
	to reading and storage. Thus began an era dominated by the paper book and the linear
	arrangement of text.
</p>

<p>
	The formal evolution of media represented a decisive advance in the transmission of
	knowledge. From stone to paper, and from cuneiform inscription to the linearity of the
	codex, each transformation improved the conditions of transmission, storage, and
	accessibility.
</p>

<p>
	Yet beneath this dynamic evolution of media forms, a voracious logic emerged: the progress of
	one medium often implied the disappearance of the one before it. The emergence of writing led
	to the disappearance of the Greek <em>aoidos</em> and to a substantial reduction in cultures
	grounded in oral transmission. Later, papyrus displaced stone and clay. In turn, the codex
	relegated the scroll. This pattern of progress through the annihilation of the previous form
	repeats itself throughout the history of media.
</p>

<p>
	Parallel to the evolution of form, the preservation of content also faced difficulties,
	especially in the struggle against textual variation. Various strategies were developed to
	minimise error: collaborative collation, in which groups compared versions during
	transcription, and the assignment of copying to trained specialists. In Hebrew culture, this
	task was entrusted exclusively to the observants of scripture. Yet even with these
	precautions, texts continued to be altered, and attempts to systematise criteria for
	correction—such as those pursued by the philologists of Alexandria—proved insufficient.
</p>

<p>
	Cultures were forced to accept these difficulties and learn to navigate them. The next
	problem was unavoidable: if textual variation could not be fully eliminated, criteria had to
	be established for selecting model versions intended for public use. This task fell to
	institutions of religious or political authority—or both—and the result of this process was
	what we now call the canon. Yet the disparity of criteria used to establish it produced deep
	disagreements and lasting consequences.
</p>

<p>
	In addition, the problem of translation brought to the surface a more complex issue concealed
	beneath variation itself: the subjective dimension of editorial practice. Attention shifted
	from the text alone to the way in which it was interpreted. Texts exist to transmit meaning,
	but that meaning is never fully transparent in itself; its understanding requires rigorous
	hermeneutic and exegetical labour.
</p>

<p>
	The full magnitude of the problem became evident when, even where different factions managed
	to agree upon a shared canon, a further dilemma emerged: what was the proper way to read it?
	Should it be interpreted literally or figuratively? These complications gave rise to enduring
	ideological conflicts, such as the division between Shiites and Sunnis in the Middle East or
	the Protestant Reformation in Europe.
</p>

<h2>The Great Division of Knowledge in the Modern Age</h2>

<p>
	For centuries, the problem of variation remained largely confined to political and religious
	disputes. Until the late Middle Ages, powerful institutions maintained control over the
	content of editions, regulating interpretation and circulation through strict systems of
	censorship.
</p>

<p>
	The invention of the printing press helped consolidate the dominance of the paper book, a
	hegemony that endured for centuries and was only challenged at the end of the nineteenth
	century and the beginning of the second millennium with the emergence of digital
	technologies.
</p>

<p>
	This development greatly accelerated progress in other fields, particularly the humanities and
	the sciences. Yet both still had to confront the subjective character of the text and the
	problem of interpretation. A decisive moment came with the work of the French philosopher René
	Descartes, who, frustrated by the obstacles subjectivity posed to the progress of knowledge,
	began a profound reflection on the proper method for constructing a stable structure of
	knowledge. With his <em>Discourse on Method</em>, the modern age begins.
</p>

<p>
	This new age was defined by a critical attitude toward tradition, one that would reach its
	emblematic expression in the Enlightenment through Kant’s famous motto: <em>sapere aude</em>
	— dare to know. Yet this critical posture proved insufficient to resolve the problem of
	subjectivity. For this reason, thinkers such as Locke and Hume pursued a more radical path
	through empiricism. According to this view, no conclusion could be considered valid unless it
	was grounded in facts. Induction thus replaced deduction as the privileged method of inquiry.
</p>

<p>
	This turn led the positive sciences into a golden age of discovery and technological
	development. Yet empirical methods proved insufficient for fields concerned with human
	experience, leaving the humanities to confront their own difficulties alone. The lack of
	agreement ultimately resulted in the famous division between
	<em>Geisteswissenschaften</em> (sciences of spirit) and
	<em>Naturwissenschaften</em> (sciences of nature).
</p>

<p>
	According to Christian Wolff, the humanities were required to apply this critical attitude at
	the level of the text’s very constitution. Rather than trusting tradition, this new method
	demanded inquiry into how tradition itself had been constructed. This procedure would later
	become known as critical edition.
</p>

<p>
	For centuries, these two branches—science and the humanities—followed separate paths, until
	new digital technologies finally opened a space for reintegration and interdisciplinary work.
</p>

<h2>Humanities in the Digital Age: Impacts of New Technologies</h2>

<p>
	The invention of the internet in the late twentieth century marked another decisive moment in
	the history of human culture and inaugurated a new era: the digital age. Recent technological
	advances and their successful implementation in the humanities have enabled the reintegration
	of what had been divided centuries earlier. The isolation of the humanities begins to close
	in the digital age. The principal impact of digital technology on this field has been to
	provide a space for reconciliation with the natural sciences and for genuinely
	interdisciplinary research.
</p>

<p>
	Another decisive impact has been digitisation as a practice of cultural preservation.
	Although digitising does not preserve the physical object itself, the value of a cultural
	object does not reside solely in its material support, but in the content it carries. The
	Rosetta Stone offers a compelling example: its immense value lies not merely in its
	materiality, but in what its content allows us to understand. Digitised, much of that value
	remains intact.
</p>

<p>
	Today, galleries, libraries, archives, and museums are the institutions charged with
	preserving the central elements of our culture. Paradoxically, these institutions are also
	fighting for their own survival. Digitisation offers both a means of generating resources
	through the circulation of digital surrogates and, more importantly, a means of preserving
	their collections.
</p>

<h2>On the Impact of Digital Technology on the Practices of Reading and Writing</h2>

<p>
	The emergence of new technologies, and especially the invention of the web, inaugurated a new
	era for editing and publishing. For the first time in nearly twenty-three centuries, the
	hegemony of the codex and the paper book was placed under threat. The web introduced a new
	non-linear way of organising text: hypertext. At the same time, advances in electronic
	devices enabled an almost identical emulation of paper, accelerating the spread of digital
	text and ushering in the age of digital editions.
</p>

<p>
	Digital editions respond directly to the central problems of the field. Once a text is
	digitised, problems of variation and corruption are almost entirely eliminated, at least for
	texts produced within this environment. Hypertextuality also makes it possible to publish
	critical editions without burdening the body of the text with editorial notes and
	interventions.
</p>

<p>
	Yet we should not be naïve. As the history of media has shown, every advance comes at a cost.
	In this case, a considerable one: the possible displacement of the printed book, one of the
	most refined forms of human culture. Digital technologies are not only reshaping physical
	reading practices, but also the earliest forms of digital writing, such as blogging.
</p>

<h2>New Challenges</h2>

<p>
	Finally, one of the most significant impacts of the digital age is the emergence of artificial
	intelligence across multiple spheres of human life. These technologies seem to inaugurate a
	new domain shaped by large language models. Their power is undeniable, but so too are their
	limitations. Despite their fluency and remarkable capacities, they still lack genuine
	world-grounding and remain without real referents.
</p>

<p>
	The danger lies not only in their technical limitations, but in the possibility of
	normalising poorly mediated machine-human interactions. These systems can simulate complex
	conversation and sophisticated traits of human behaviour, yet the case of Weizenbaum reminds
	us of the grave risks posed by intelligence without empathy. Human life is composed not only
	of language and reason, but also of emotion, vulnerability, and care.
</p>

<p>
	More than progress, intelligence becomes a danger when it is not guided by ethical
	principles. The same is true of artificial intelligence: it becomes perilous when used to
	subjugate rather than emancipate, to control rather than liberate. The central question,
	then, is how to establish limits and ethical principles capable of guiding these
	developments.
</p>

<p>
	The fundamental principle remains simple, though difficult to sustain: we are in this world
	not only to think, but also to care. Care for others and for the world must remain the
	guiding principle of any future intelligence. To recognise this does not resolve the problem,
	but it is already a decisive step toward a more just society.
</p>
