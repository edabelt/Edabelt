                <h3>Node 2.1</h3>

                <p>—Vahlia: Who are you?</p>

                <p>
                    My name is Yuuban Yataque, which means “Living Earth” in my native tongue. I belong to the
                    Amazonian tribe of the Yanihuír.
                </p>

                <p>—Vahlia: Coming from so far away, you must be searching for something important in these lands.</p>

                <p>
                    —Yuuban: Truthfully, all I do is search for original sunsets, hoping that somewhere within
                    the dawns I might stumble into some impossible predicament capable of giving meaning to my
                    life.
                </p>

                <p>
                    —Vahlia: Then you have very few sunsets left if you refuse to take my interrogation
                    seriously!
                </p>

                <p>
                    —Yuuban: But I am serious. I tell you, I wander the world collecting sunsets.
                </p>

                <p>
                    —Vahlia: Then tell me: what kind of sunset did you come seeking in this place?
                </p>

                <p>
                    —Yuuban: I truly do not know. I only remember witnessing the photogradual eclipse somewhere
                    in a remote corner of the northern hemisphere and, without understanding how, appearing here,
                    where the monotony of the sunsets saddens my nights, though I sleep upon a bed of white
                    petals.
                </p>

                <p>
                    —Vahlia: Hm. There is some truth in your words, but I cannot tolerate your lack of rigour.
                    Allow me to help you refine your answers. What I mean is this: what were you searching for in
                    this region of the island?
                </p>

                <p>
                    —Yuuban: You mistake my ignorance for a lack of rigour. To begin with, I was not even certain
                    this place was an island. I merely suspected it because I had encountered no one besides the
                    “Palm Man,” and because I had eaten nothing but salty fruits. Once, I glimpsed what appeared
                    to be a ploughed field, with perfectly ordered furrows, beyond a hill strewn with monolithic
                    stones. I travelled there hoping to find human presence. And look — I found it indeed! Here
                    I am, awakening bound to a tree in yet another magnificent dawn bestowed upon me by the human
                    hand.
                </p>

                <p>
                    —Vahlia: Let me organise your thoughts a little. First: he is not a “Palm Man,” but a member
                    of the Cocotuah tribe. Second: the fruits are not salty — you are displaying symptoms of
                    taste distortion.
                </p>

                <p>
                    —Yuuban: Wait, wait, wai… I cannot follow you when your reasoning stretches on for so long…
                </p>

                <p>
                    —Vahlia: And you shall understand me even less if you keep interrupting me while I speak!
                </p>

                <p>
                    Third: it is not a “ploughed field,” but my weekly chronicle. Fourth: what you call
                    “monolithic stones” are, in fact, heaps of beetle excrement. Fifth: we are nowhere near
                    dawn. And finally, you are not tied to any tree — I wrapped you in medicinal bark and roots
                    to alleviate your symptoms.
                </p>

                <p>
                    —Yuuban: Forgive the interruption. It is simply that, apart from the part about the
                    excrement, I understood almost nothing you said. Perhaps you should begin by explaining what
                    you mean by “taste distortion.”
                </p>

                <p>
                    —Vahlia: <em>Echt?</em> That was not the first point, but the second. With such a lack of
                    rigour, I fail to understand how you speak German so well.
                </p>

                <p>
                    —Yuuban: In any case, I would like you to clarify why you are saying all this. What is it
                    that you do? What exactly is this chronicle? And what symptoms are you talking about?
                </p>

                <p>
                    —Vahlia: Listen carefully. I came to this island because an uncontacted population lives
                    here. They practise an ancestral medicine that represents the only hope against one of the
                    great plagues devastating the planet. I must obtain that medicine. Yet time is running out.
                </p>

                <p>—Yuuban: Time for what?</p>

                <p>
                    —Vahlia -through tears: To evacuate the native population. I always recorded my discoveries
                    in a journal, but I lost it when a great tidal surge — the very same that brought you to this
                    island — erased everything I had written in the sand. The arrival of those frozen torrents
                    proved to me that it is already too late: the thawing of the sacred glaciers has begun. The
                    only thing left for me is to leave behind solid traces that survivors once existed here.
                    So I searched for a clearing protected by the hill and by the fetid stench of insect dung.
                    There, I planted palm trees in patterns recounting the events that have unfolded since the
                    photogradual solar eclipse. The labour of planting is so exhausting that I can no longer keep
                    a conventional journal, and so I decided instead to “sow” the lines of a weekly chronicle.
                </p>

                <p>
                    —Yuuban -with sarcasm: Ah, wonderful. Everything you are telling me fills me with dread and
                    bewilderment. So tell me… are we going to drown on this island?
                </p>

                <p>
                    —Vahlia: Quite possibly. But if you help me carry out my escape plan, at least I may still
                    take the sacred remedy with me.
                </p>

                <p>
                    —Yuuban: At this point, I know that questioning you further will only leave me more confused
                    than before. Besides, I am clumsy at interrogations; I rarely have anyone near enough to
                    question. Facts and adventure interest me far more. So tell me plainly: what must I do?
                </p>

                <p>
                    —Vahlia: You must infiltrate the Cocotuah tribe. You will succeed only if you follow my
                    instructions to the letter.
                </p>

                <p>
                    —Yuuban: And if you are the rigorous one, why have you not done it yourself?
                </p>

                <p>
                    —Vahlia: Truthfully… I am incapable of dancing.
                </p>

                <p>
                    —Yuuban -ironically: Yes, that much has become abundantly clear. Then let me go.
                </p>

                <p>
                    —Vahlia: I have little choice. I only hope I have not fallen victim to your deception.
                </p>

                <p>
                    —Yuuban: Deception is not my craft. It is the invasions of others that force me into becoming
                    what I never intended to be. I love only my freedom. Farewell, nameless blonde.
                </p>

                <p>
                    —Vahlia -laughing: My name is Vahlia Rigursson, and I belong to the peoples of the North.
                </p>

                <p>
                    —Yuuban: I know some of those peoples, and I admire them. Yet my roots were planted much
                    farther south.
                </p>

                <p>
                    —Vahlia: Before you leave, take some of this brew I have managed to prepare. It is not a
                    cure, but it will serve as a palliative once your symptoms intensify. The antidote can only
                    be extracted from the sacred giant coconut. That is why you must go in search of it.
                </p>

                <p>
                    —Yuuban: Wait… what symptoms are you talking about?
                </p>

                <p>
                    —Vahlia: You suffer from a terrible illness.
                </p>

                <p>
                    —Yuuban: Ha! Without question, I suffer from boredom in the face of monotonous sunsets.
                </p>

                <p>
                    —Vahlia: That is not what should concern you. Here, you shall see them growing closer and
                    closer: the Sun is becoming a red supergiant.
                </p>

                <p>
                    —Yuuban: Ah, I see… Then what exactly should I be worried about?
                </p>

                <p>
                    —Vahlia: Yuuban of the Yanihuír tribe… you carry the plague.
                </p>

