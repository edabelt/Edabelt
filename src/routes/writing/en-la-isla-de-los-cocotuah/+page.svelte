                <h3>Node 2.1.1.2</h3>

                <p>
                    More than several harvests have passed since my last encounter with Vahlia. At times I feel
                    like a traitor, yet… a traitor to what, exactly? After all, I do not believe Vahlia could
                    have truly done anything with the information I gave her. Besides, if everything she says is
                    true, then the salvation of many people depends upon her success. In any case, such remorse
                    fades whenever I immerse myself in the collective labours of the tribe.
                </p>

                <p>
                    I now understand their body language far better and participate, like any other member, in
                    all the activities of the tribe. I even understand their humour and dare to tell a few jokes
                    through ridiculous dances. I have not forgotten spoken words, but neither do I miss them.
                </p>

                <p>
                    I have perfected several palm-weaving techniques to craft garments and ceremonial attire for
                    each member of the tribe. I have also learned to perceive the new colours the Sun reveals
                    through its growing gigantism, and I apply those exotic combinations to my weavings. At this
                    very moment, I am occupied preparing the attire for my consecration choreography, which I
                    must present before the entire tribe during the great celebration.
                </p>

                <p>
                    By the sixth harvest, tribe members are finally considered ready for the rite of consecration.
                    For the first time, I shall lead the dances during the nocturnal gatherings. I am equally
                    eager to taste, for the first time, the Drink of Joy and discover the sidereal dances of
                    which Two Palms so often speaks.
                </p>

                <p>
                    For my presentation, I chose “Bound Fingertips” as my dance companion simply because I loved
                    her name. To represent it, we press together the tips of every finger and slowly bend the
                    index phalanges inward until our nails meet. Nearly everything is ready now: today we held
                    the final rehearsal wearing the ceremonial garments we shall don tomorrow.
                </p>

                <p>
                    At last, the great day has arrived. I stand fasting beside the elders, carrying out the final
                    meditation before beginning the dances of consecration for the tribe… my tribe. The emptiness
                    of my mind is suddenly interrupted by the mere awareness of my companion’s presence: I feel I
                    could sense her and dance beside her even from miles away. The murmur of the procession draws
                    nearer. Incense thickens the air within the enclosure. Then my companion’s hands entwine with
                    mine: the moment has come to offer our dance of consecration to the tribe.
                </p>

                <p>
                    Suddenly, our dance is shattered by an ineffable chant rising from the western horizon.
                    Everyone reacts in bewilderment, colliding with one another and covering their ears against
                    the music, which proves overwhelming to most. Some of us rush toward the shores lined with
                    lush fruit groves as the chant grows louder and louder. When I finally reach the end of the
                    palm forests, I witness for the first time my entire tribe dissolving into cries and tears.
                </p>

                <p>
                    From among the fluorescent fruit trees emerges a sled transformed into a gigantic tricycle,
                    with three colossal coconut rings serving as wheels. At its centre, a woman drives a pulley
                    system through powerful, relentless pedalling, while upon the rear of the strange vehicle
                    rests the sacred giant coconut.
                </p>

                <p>
                    As it reaches the shore, a pod of cetaceans harnessed with vines begins to sing the ineffable
                    songs of departure. The charioteer seizes the reins and, without ceasing to shake them,
                    pushes onward into the open sea. Her golden hair billows above the waves as though she were
                    Helios himself guiding his chariot across the heavens, or Prometheus fleeing after stealing
                    fire from the gods.
                </p>

                <p>
                    Farewell, Vahlia of the northern peoples.
                </p>

                <p>
                    The sublime vision is suddenly broken by the laughter of an unexpected spectator.
                </p>

                <p>
                    —So, you came all this way to spread the plague as well? In this infernal heat, you had
                    better teach me how to sweat ice if you ever hope to escape alive again.
                </p>

                <p>
                    And then I succumb, crushed within the overwhelming grip of Ruslans hand.
                </p>
