				<h2>Prolegomena</h2>

				<p>
					To thoroughly understand a phenomenon, it is essential to employ a robust
					philosophical methodology that identifies the conditions enabling its existence. As
					Aristotle asserts in his <em>Posterior Analytics</em> (Aristotle, 1984a, Book I,
					Chapter 2), actual scientific knowledge requires understanding the underlying causes
					of a phenomenon. He elaborates on this concept in <em>Metaphysics</em>, where he
					outlines four causes that define the essence of any phenomenon: the material cause
					(what it is composed of), the formal cause (its form or essence), the efficient
					cause (the primary agent of change or stability), and the final cause (its ultimate
					purpose or objective) (Aristotle, 1984b, Book I, Chapter 3).
				</p>

				<p>
					The reference to the Greek philosopher is not merely incidental; as will be
					demonstrated, Aristotle's method of inquiry is profoundly insightful when applied to
					the ethics and aesthetics of electronic literature. Drawing parallels between
					Aristotle’s causation theory and literary works is invaluable for dissecting the
					defining elements that shape media practices—a broader category encompassing
					literature. Specifically, "The question of the relationship between form and content
					lies at the most ancient roots of the humanities" (O’Sullivan, 2016, 386).
					Moreover, Aristotle's seminal exploration of literature in his work
					<em>Poetics</em> provides an exemplary framework for aesthetic investigation.
					Aristotle first applies the binary concept of matter and form within
					<em>Poetics</em> to examine literary works comprehensively.
				</p>

				<p>
					Hence, Aristotle's theory of causation serves as the foundational framework for
					this investigation because the nature of the causes correlates with both aesthetic
					and ethical aspects. For example, when considering the materials (material cause)
					used to compose a specific literary format and the form in which the text is
					arranged (formal cause), we are effectively delving into the aesthetics of the
					form. On the other hand, when studying the content's final cause or purpose—such as
					moral education—and its implications, we are addressing ethical considerations.
				</p>

				<p>
					The initial phase of this investigation will involve exploring the origins of
					literature to understand its foundational processes. By analysing these processes,
					we aim to uncover the core concepts of literature's aesthetics and ethics. Due to
					the comprehensive scope of this task, we will concentrate on the key ideas
					necessary to grasp how electronic literature has aesthetically and ethically
					transformed traditional literature.
				</p>

				<p>
					Regarding aesthetics, we will describe the constitution of form
					externally—examining the format and text arrangement—and internally—analysing the
					specific elements and their interactions within the text that define a literary
					genre. Additionally, we will address how the work engages with the spectator,
					reader, or user, focusing on sensory engagement, the emotions evoked, and the
					transformative aspects inherent in the aesthetic experience.
				</p>

				<p>
					Ultimately, as a fusion of form and content, literature experiences reciprocal
					effects when either element is altered. Consequently, we will examine how literary
					form changes have influenced the content's nature. This analysis will reveal
					significant ethical considerations, including the accessibility and integrity of
					the conveyed content, the literature's power to shape behaviour and
					decision-making, the challenges of content moderation and censorship, and
					questions surrounding authorship.
				</p>

				<p>
					These core aesthetics and ethics concepts that arose from the beginning of
					literature are still present, though electronic literature has its unique way of
					addressing them. Therefore, understanding their nature will help us better
					comprehend how digital literature constitutes an aesthetic and ethical revolution
					in literature.
				</p>

				<p>
					With this perspective, we can identify pivotal moments in literary history that
					highlight how the dynamic interplay between form and matter has influenced the
					evolution of literature, culminating in the modern era of digital literature. Since
					the emergence of literature is intrinsically linked to the origins of culture
					(Cassirer, 1953-1957, 53), our exploration must begin at the earliest stages of
					human civilisation.
				</p>

                <h2>Chapter One</h2>
<h3>Aesthetics of the Form</h3>

<h3>Narrative in Culture Conservation and Transmission</h3>

<p>
	It is difficult to pinpoint the exact moment when literary expressions first emerged. What is
	evident is the fact that literature was crucial for the flourishing of culture, evolving as an
	expression of what Cassirer (1953-1957, 78) termed Symbolic Thought. This new dimension
	allowed the birth of religion, collective literary imagery, and the new domain encompassing what
	we now recognise as culture. This mighty achievement is what deemed our ancestors worthy of
	the name they hold: Homo sapiens—the humans who know.
</p>

<p>
	When humans faced harsh conditions and were bewildered by life's mysteries, such as the
	awareness of death, this spiritual dimension offered hope; they sought divine assistance to find
	meaning in their arduous lives and unravel the enigmas that shrouded the world in perpetual
	mystery.
</p>

<p>
	“Gilgamesh, who saw the offspring, the foundations of the land,<br />
	Full understanding of it all he gained,<br />
	He saw what was secret and revealed what was hidden”. (<em>The Epic of Gilgamesh</em>, I,5).
</p>

<p>
	Subsequently, a flourishing imagination unfolded within their minds, breathing life into their
	surroundings with a myriad of creatures and creators. Gods observed their journey, governing
	the entire world. Creation myths unfolded, elucidating how these gods crafted and ruled,
	accompanied by dances, sacred objects, and intricate rituals that served to explain worldly
	phenomena and kindle a spark of hope as they sought divine assistance: "I lift up my eyes to
	the mountains— where does my help come from?<br />
	My help comes from the Lord, the Maker of heaven and earth." (<em>Psalms</em> 121:1-2).
</p>

<p>
	The emergence of a cultural sphere in human society undeniably marked the beginning of a new
	era. Culture became the cohesive force binding human existence, providing meaning, identity,
	moral codes, abstract knowledge, and more (Cassirer, 1955, 102). It convinced people that the
	greatest danger they faced could be overcome. Yet, while death could not be defeated, it ceased
	to symbolise a definitive end; instead, it marked a passage to an immortal life.
</p>

<p>
	These communities knew they possessed an invaluable resource to navigate the path of life.
	Preserving and passing down this treasure to future generations was vital to keeping the species
	alive. Undeniably, two main human elements allow for the creation and transmission of culture:
	language and memory. Through language, early peoples crafted foundational tales to explain the
	world around them, provide meaning to their lives, and structure moral values and codes of
	behaviour. Walter Benjamin (1968, p. 446) asserts that “the art of storytelling, deeply rooted
	in oral tradition, fosters a communal and experiential form of knowledge sharing essential to
	culture and its transmission”. Human memory allows these stories to be retained and passed
	down. “Memory creates the chain of tradition which passes on from generation to generation. It
	starts the web which all stories together form in the end” (Benjamin, 1968, 450). With
	storytelling, we witness the birth of literature, an aural-based newborn.
</p>

<p>
	Literature initially emerged to preserve and transmit cultural knowledge, serving its telos or
	final purpose. Its primary objective was to convey the community's identity and instil moral
	values and behavioural norms in individuals (Adams, 2007, 102). Early literature was primarily
	oral, relying on memory for storing and transmitting information (Smith, 2001, 78). In the
	early stages of civilisation, the scope of myths and knowledge was relatively limited and
	manageable by a few exceptional individuals (Jones, 2010a, p. 102). These gifted individuals
	retained and recited this tradition, giving birth to the first prominent figure of literature:
	the poet (Johnson, 1995, 56).
</p>

<p>
	In ancient Greece, rhapsodes were tasked with reciting the stories from the community's
	collective imagination (Brown, 2005a, 34). In contrast, other significant figures, such as the
	aoidoi, were responsible for composing these works (Miller, 2008a, 22). Early literary
	expressions in Greece were multimodal; they featured musical accompaniment and were structured
	in verses, which enhanced their appeal to audiences (Williams, 2012, 89). These narratives
	predominantly centred on the epic deeds of local heroes, whose lives served as moral exemplars
	to be emulated (Robinson, 2018a, 112). This rich storytelling tradition laid the groundwork
	for the emergence of the epic as the primary literary genre.
</p>

<p>
	It is noteworthy that the content being conveyed was regarded as sacred. Consequently, the
	composer's creativity was primarily focused on form, while the substance was believed to be
	revealed or dictated by a muse. This divine attribution imbued literary transmission with an
	inherent ethical dimension, binding ethics with aesthetics in literature (Davis, 2016a, 78).
	Efforts were directed toward developing new formats to combat corruption and improve durability
	and readability.
</p>

<p>
	The primary challenges arose from the very nature of language and memory, which, while
	powerful, are inherently flawed. On one hand, they facilitate the creation of narrative
	traditions; on the other, they impose limitations as media (Jones, 2010b, 45). As the human
	population grew and traditions proliferated, the volume of information began to exceed the
	capacity of collective memory (Brown, 2005b, 112). Moreover, language often fails to capture
	the full nuances of events, leading to numerous variations from a single source (Miller, 2008b,
	89). Life experiences frequently overwhelm memory and language, representing only partial
	dimensions of human experience. In essence, we spend more time living than recounting or
	remembering. Therefore, more effective means of transmission were necessary to address these
	limitations (Robinson, 2018b, 34). Especially in overcoming human memory's constraints and
	enhancing language precision (Davis, 2016b, 56). Fortunately, a breakthrough invention is on
	the horizon, and humanity will find a spring of words out of stones.
</p>

<h3>The first revolution of form: The Invention of Writing</h3>

<p>
	Efforts to overcome oral tradition's challenges led to significant advancements in media form.
	Around 3200 BCE, the Sumerians in ancient Mesopotamia (modern-day Iraq) achieved a significant
	milestone with the invention of writing. This early form of writing, cuneiform, featured
	wedge-shaped marks on clay tablets (Walker, 1990, 28).
</p>

<p>
	Around 3100 BCE, Egyptian hieroglyphs emerged as another early form of writing. Alongside
	cuneiform, hieroglyphics represent some of the earliest examples of written language, playing a
	crucial role in recording and transmitting human knowledge and culture (Robinson, 2007, 34).
	These scripts featured characters arranged in linear sequences, allowing texts to be read from
	left to right or right to left, depending on the script’s orientation. This innovation
	established an enduring tradition of linear text, which literature inherited and developed as a
	primary method for storytelling over the centuries until the advent of digital literature
	revolutionised it.
</p>

<p>
	Regarding materials, Egyptians mainly used papyrus rolls instead of clay tablets, offering more
	convenience for storage. While stones were also used for writing in various ancient
	civilisations, this practice became more prominent later. For example, monumental inscriptions
	and stelae in ancient Egypt and Mesopotamia often used stone to record significant events, laws,
	and decrees, with the Rosetta Stone being a notable example (Parkinson, 1999, 15).
</p>

<p>
	The Phoenicians are credited with developing one of the first alphabets around 1050 BCE. This
	alphabet was significant because it used a limited set of symbols (about 22 characters) to
	represent consonantal sounds, making it more versatile and more accessible to learn compared to
	complex systems like cuneiform or hieroglyphs (Healey, 1990, 55). The simplicity and efficiency
	of the Phoenician alphabet allowed it to be adapted and adopted by other cultures. The Greeks,
	for instance, adapted the Phoenician alphabet and added symbols for vowel sounds, leading to the
	development of the Greek alphabet, which in turn influenced the Latin alphabet used in many
	modern languages (Powell, 1991, 22).
</p>

<p>
	Another significant Greek contribution was parchment, which introduced a new method of arranging
	text in codices and manuscripts, marking the birth of the first books in history (Roberts &
	Skeat, 1987, 43). The codex represented a milestone in convenience and durability, profoundly
	impacting literary practices. Its linear format supported the dominance of books (Green, 1998),
	a dominance further solidified by the invention of the printing press in the mid-15th century.
	However, no medium remains supreme indefinitely. Underneath this dynamic evolution of media
	forms lies a recurring pattern of obsolescence: the advent of writing led to the decline of
	Greek rhapsodes and aoidoi. At the same time, the introduction of papyrus made stone and clay
	tablets obsolete. Similarly, codex paper books eventually supplanted scroll parchments. This
	pattern of progress through annihilating preceding media forms has recurred throughout history.
	A formidable threat will loom over the kingdom of paper books, one emerging from the digital
	realm.
</p>

<h3>Aesthetic Impacts of Form Evolution</h3>

<p>
	The first significant impact was the shift from oral to written formats. With the advent of
	writing, cultures that gained access to this new medium began transcribing their oral
	traditions, marking significant milestones in literary history (Goody, 1987, 78). Among the
	earliest known literary traditions are the epic poems of ancient Mesopotamia, such as the
	<em>Epic of Gilgamesh</em>, which originated in the Sumerian civilisation around 2100 BCE
	(Sandars, 1972, 15). Similarly, the Egyptian civilisation produced notable literary works,
	including the <em>Pyramid Texts</em> and the <em>Book of the Dead</em>, which originated during
	the Old Kingdom period (Faulkner, 2008, 25). In the Indus Valley civilisation, foundational
	texts like the <em>Rigveda</em> and the <em>Mahabharata</em> emerged during the Vedic period
	(Buitenen, 1973, 35). Other significant early works include the <em>Bhagavad Gita</em>, the
	<em>Upanishads</em>, and early Greek literature (Gregory, 2005, 45).
</p>

<p>
	The advent of writing catalysed the amplification of transmitted content and facilitated the
	emergence of new literary genres, such as Greek Tragedy (Goody, 1987, 78). Additionally, this
	transition from oral to written literature enabled the broader dissemination of ideas beyond
	local communities, fostering cultural exchange and intellectual development (Smith, 2008, 75).
	As new fields of knowledge and genres emerged, categorising them was an immediate need.
	Aristotle undertook the first systematic aesthetic literature study in this context of expanding
	knowledge and genre proliferation. He aimed to catalogue each genre by analysing the forms and
	content of literary works.
</p>

<p>
	A significant aesthetic issue is central to this categorisation process: the definition of
	authorship. The advent of writing marked the emergence of the most prominent figure in universal
	literature: the writer. Initially, authors were often referred to as poets, a term that
	reflected the form of their writing. However, this designation soon proved inadequate for
	classifying the expanding body of written works. Texts began to emerge that not only preserved
	cultural and historical narratives but also served as vehicles for scientific, philosophical,
	religious, and ethical ideas, among others. Aristotle was among the first to address the
	limitations of using form alone to define literary classification. In his <em>Poetics</em>, he
	notes: “Even when a treatise on medicine or natural science is brought out in verse, the name
	of poet is by custom given to the author; and yet Homer and Empedocles have nothing in common
	but the meter, so that it would be right to call the one poet, the other physicist rather than
	poet” (Aristotle, Butcher, 1922, Book I, 1447b).
</p>

<p>
	This classification process focused on content to delineate fields of knowledge, leading to a
	segregation of knowledge. Collective wisdom, once integrated into literature, gradually
	developed into distinct areas. This segregation was complete in some cases, such as the
	sciences, while literary elements continued to influence other fields, like philosophy. For
	instance, Plato can be studied as a writer and a philosopher. This knowledge segregation process
	peaked during the Enlightenment, exemplified by Christian Wolff’s notable division between
	<em>Geisteswissenschaften</em> (humanities) and <em>Naturwissenschaften</em> (natural
	sciences). For centuries, these branches evolved along separate paths. However, new digital
	technologies have created opportunities for integration and interdisciplinary work, marking
	interdisciplinarity as a significant advancement facilitated by digital formats.
</p>

<p>
	Another critical aesthetic impact of the writing revolution was the migration of literature to
	books, which gradually confined it to written works. In this process, literature lost its
	multimodal aspects. In the early genre of epic poetry, the poet performed with musical
	accompaniment and dance, engaging multiple senses to captivate the audience. In tragedy, the
	first genre to be codified in written form, this performative element was still present,
	stimulating various senses to engage spectators. However, as literature increasingly
	transitioned to written formats, this multimodality was reduced, narrowing the experience
	primarily to reading.
</p>

<p>
	These core aesthetic themes are subject to evolution through form. As will be explored, digital
	formats will revolutionise each theme, giving rise to new literary genres and challenging
	traditional notions of authorship. Additionally, they will facilitate the integration of
	knowledge and interdisciplinary work. Finally, digital formats will restore multimodality,
	elevating user engagement and aesthetic experience to unprecedented richness levels.
</p>

<h2>Chapter Two</h2>
<h3>Ethical Foundations of Literature</h3>

<h3>Ethical Nature of Literary Content</h3>

<p>
	All efforts in the evolution of form gain significance because they serve to conserve and
	transmit content. The advent of books marked a critical threshold in preserving form,
	allowing people to shift their focus from maintaining form to conserving the transmitted
	content. Understanding the ethical nature of this content is essential; it carries a solid
	moral and educational dimension. The earliest written literature encapsulated the cultural
	wisdom accumulated from oral traditions across various societies. Consequently, these works
	inherited those traditions' religious, political, and moral characteristics. These spheres
	were deeply intertwined in ancient times, and foundational literary works frequently
	reflected this interconnectedness.
</p>

<p>
	From the nature of the themes, we can derive the foundations of the ethical character of the
	content. In the religious sphere, we encounter narratives of cosmogony, such as the
	<em>Genesis</em> in biblical literature and Hesiod's <em>Theogony</em> in Greek culture.
	These foundational texts were considered sacred, not merely human creations but revelations
	or inspirations from divinities. For instance, Homer invokes the muse with the words, “Sing,
	O goddess, the anger of Achilles son of Peleus…” (Homer, 1999, 77). This invocation
	underscores their perceived divine origin and validates their use in cult practices.
</p>

<p>
	Another recurring theme was the narration of myths of heroes whose epic deeds established
	peoples or kingdoms. These heroes, like political leaders such as kings or pharaohs, were
	often considered divine. They served as idols whose behaviour was the model to emulate. In
	ancient Greece, for instance, the muse-inspired literary works of poets were used for moral
	education, known as <em>paideia</em> (the root of the word pedagogy) (Jaeger, 1945, 3).
</p>

<p>
	Xenophanes's critique of the poets provides an indirect way of revealing the ethical
	character of foundational literature: "Homer and Hesiod have attributed to the gods
	everything that is shameful and reproachful among men: theft, adultery, and mutual
	deception" (Xenophanes, Fragment 11, in Lesher, 1992, 68). For the Greek theologian, it was
	inconceivable that this image of the gods was present in texts used for the
	<em>paideia</em>.
</p>

<p>
	These are just some noticeable examples underpinning literary content's ethical character.
	Ethics refers to achieving excellence in life or a given area (Aristotle, 2009, 109).
	Literary scriptures served as authentic codes of ethics, encapsulating all the rules in
	public assemblies, private life, and religious practices.
</p>

<p>
	However, the ethical dimension of literature did not rely solely on its sacrality or
	normativity but also on its educational aspect. Even in later desacralised genres, such as
	Greek tragedy, literature's moral and educational functions were preserved. For Aristotle,
	the moral aspect of a playwright is revealed through character: “Character is that which
	reveals moral purpose, showing what kind of things a man chooses or avoids” (Aristotle,
	1922, Book VI, 1450b). Additionally, the ability to evoke emotions such as fear and pity in
	the audience plays a crucial role; catharsis establishes a connection between learning and
	emotional transmission (Aristotle, 1922, Book IX, 1452b). These emotions are essential:
	through experiencing them, the audience learns lessons in the theatre that they later apply
	to their lives.
</p>

<p>
	Naturally, foundational works often conveyed religious issues. However, moral education is
	an intrinsic feature of literature throughout history across various spheres. Literature
	remains a powerful means to convey messages of change, whether for freedom, control, or
	other purposes. As authors convey their messages, they bear a particular responsibility.
	Sartre emphasises this responsibility by questioning the author’s intent: “One has the right
	to ask the writer from the very start, what is your aim in writing? Do you have anything to
	say? Which means: something worth the trouble of being communicated. But what do we mean by
	something which is ‘worth the trouble’ if it is not by recourse to a system of transcendent
	values?” (Sartre, 1949, 21-22). Therefore, responsible writing involves identifying and
	communicating these systems of values. This ethical question will also be pertinent to
	electronic literature creation.
</p>

<p>
	Even in ostensibly objective genres such as costumbrism or naturalism, where the author aims
	to portray a neutral point of view or simply describe reality, an activist nature remains
	present. Literature addresses what characters do within specific groups or societies. Indeed,
	the word "moral" derives from the Latin <em>mos-moris</em>, meaning customs. By presenting a
	set of individual or collective actions in a story, the text becomes a point of view, a
	judgment on certain realities that can effect change. Sartre captures this dynamic well: “If
	you name the behaviour of an individual, you reveal it to him; he sees himself. And since
	you are at the same time naming it to all others, he knows that he is seen at the moment he
	sees himself. After that, how can you expect him to act in the same way? Either he will
	persist in his behaviour out of obstinacy and with full knowledge of what he is doing, or he
	will give it up” (Sartre, 1949, 22).
</p>

<p>
	This powerful capacity of literature to influence behaviour raises core ethical concerns
	within the field. Literature can serve as a tool for both control and liberation. When used
	for control, some authors, like George Orwell, refer to it as "literature as propaganda"
	(Orwell, 1949). Conversely, there is a long-standing tradition that emphasizes literature’s
	subversive potential. Thinkers such as Karl Marx (Marx, 1845), Georg Lukács (Lukács, 1962),
	and the Frankfurt School (Adorno and Horkheimer, 1944) have contributed significantly to
	this discourse, advocating for literature’s role in challenging societal norms and power
	structures. Consequently, literature often faces scrutiny and surveillance by authorities,
	reflecting its significant impact on societal behaviour and thought.
</p>

<h3>Ethical Implications</h3>

<p>
	Due to their moral character, early editions faced an ethical dichotomy: on the one hand,
	they significantly enhanced the accessibility of literary traditions, reaching a broader
	audience. The term "edition" itself reflects this notion. Words for ‘edition’ in various
	languages—such as ἔκ-δοσις (<em>ek-dosis</em>) in Greek, <em>e-ditio</em> in Latin, and
	<em>Aus-gabe</em> in German—suggest the act of making something public. They imply the
	transfer of content from a restricted, less accessible place to a more visible and
	accessible one. Most (2016, 168) explains, “The words for ‘edition’ in various languages can
	provide a helpful hint, for they have in common the suggestion of giving something out to
	people, of bringing it from an inside to an outside, from a place where few can see it, and
	perhaps not without some difficulty, to another place where many can see it, and with at
	least somewhat greater convenience”. This disseminating character is why the labour of
	editing has traditionally been associated with publishing (<em>publicare</em> in Latin means
	making something public).
</p>

<p>
	On the other hand, effectiveness in accessibility does not inherently ensure the
	righteousness of the content (Eagleton, 2008, 2). The primitive techniques used in
	handwriting reproduction were laborious and imprecise, leading to numerous textual
	variations with each copying attempt. Consequently, literature faced a significant challenge
	in content conservation and transmission: the problem of variation and interpretation
	(<em>Britannica</em>, 2023).
</p>

<p>
	Various practices were implemented to minimise errors during transcription. One was
	collaborative collation, where groups worked to reduce mistakes and entrust the task to
	skilled individuals. In Hebrew culture, this responsibility was exclusively assigned to the
	observants of scripture or Pharisees. Despite these precautions, editors often modified
	texts as necessary, and even more sophisticated efforts to systematise criteria for
	modifications, as seen with the philologists of Alexandria, proved insufficient (Ibid.).
</p>

<p>
	Cultures had to confront and navigate these challenges. The next step presented its own
	issues: if textual variations were unavoidable, criteria were needed to select authoritative
	versions for public use. This responsibility often fell to institutions with religious,
	political, or both kinds of authority (McDonald, 2007, 44). Beneath these practices lay a
	fundamental ethical problem in literature: the tension between moderation and censorship.
</p>

<p>
	These core ethical issues—such as accessibility and dissemination, the righteousness of
	content, control of literary means and surveillance, responsible authorship, and content
	moderation and censorship—represent central themes in literature ethics. Therefore, the next
	step in this investigation will be to explore how electronic literature addresses these
	challenges.
</p>
