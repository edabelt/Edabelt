				<h2>Chapter IV</h2>
				<h3>Ethics of Digital Literature</h3>

				<h3>Preservation and Transmission in a Data-Oriented World</h3>

				<p>
					Ethics, like many philosophical concerns, often extends across multiple disciplines.
					For this reason, before proceeding, it is necessary to define the perspective from
					which these issues will be addressed. Throughout this investigation, we have already
					established the framework in which ethical discussions are situated. We began by
					examining the relationship between ethics and aesthetics in literature, emphasizing
					how literary form and content mutually shape one another.
				</p>

				<p>
					The emergence of written literature introduced decisive ethical considerations that
					laid the foundations for the issues now under examination. Drawing from the
					parallel between the written and digital revolutions, we now consider the ethical
					implications of digital transformation in literature, focusing on the central
					questions previously outlined and exploring how they manifest in digital contexts.
				</p>

				<p>
					It is worth recalling that the primary aim of literary media is to facilitate the
					preservation and transmission of human culture. From this premise, the first task is
					to examine how these ends are affected in digital environments. Digitisation offers
					a new domain in which literary goods may be preserved more efficiently than in
					physical media. In this respect, electronic literature improves form and supports
					the preservation of content.
				</p>

				<p>
					This improvement also extends to the transmission of literature. The emergence of
					the internet has contributed to what is often described as a “smaller world,” in
					which digital goods may be accessed from nearly any connected location, reaching
					unprecedented levels of availability.
				</p>

				<p>
					As a result, the creation of digital resources is increasingly guided by FAIR
					principles: findability, accessibility, interoperability, and reusability
					(Wilkinson et al., 2016). Yet the ethical challenge lies not merely in promoting
					these principles, but in ensuring that they are meaningfully enacted in relation to
					the institutions, technologies, and publics involved.
				</p>

				<p>
					Here the first ethical concerns emerge. With regard to preservation, the initial
					question is what precisely is being preserved in digital goods. Secondly, ethics
					demands that transmitted content be made accessible and distributed justly among
					all users.
				</p>

				<p>
					A significant concern in the philosophy of digital technology is how emerging
					technologies shape the structure of the world itself. In the previous chapter, we
					examined how computational limits ultimately constrain the sophistication of form
					and features such as interactivity and agency. Electronic literature, in
					particular, exists within the broader condition of a data-oriented world.
				</p>

				<p>
					Ernst Jünger (1989) argues that digital technologies structure the world as a field
					of data, while human response functions as a processor integrating these elements.
					In reflecting on this fusion of the digital and the real, Vincent Blok (2017, 45)
					observes that “in the digital age we are not confronted with singular inventions
					like the telescope, but with a set of interconnected and interdependent
					technologies, such as sensors for data collection, data processing, and
					interconnected technological ecosystems.”
				</p>

				<p>
					This perspective underscores that digitisation leads to the datafication of the
					world. Wheeler (2002) argues that the central assumption of digital physics is that
					the universe is composed of informational bits, suggesting that all physical
					entities derive from data. This view aligns with the empiricist assumption that the
					world is measurable, while digital measurement reduces experience to units of data.
					As a result, new norms and patterns emerge from these data structures, often
					reproducing cycles of bias and reductionism grounded in their own assumptions.
				</p>

				<p>
					As a consequence, digital works risk gradually losing their qualitative properties.
					Recent technologies such as artificial intelligence, augmented reality, and virtual
					reality offer unprecedented levels of simulation and immersion, yet they remain
					anchored in a data-oriented world.
				</p>

				<p>
					Although these technologies demand recognition for their sophistication, it is
					equally necessary to acknowledge that such digital realities are always preselected
					and filtered. This process reconfigures fundamental human categories such as space
					and time, as experience becomes progressively less dependent on physical location
					and proximity.
				</p>

				<p>
					When speaking of accessibility, it is also necessary to consider its limits. The
					seemingly boundless potential of digital goods does not amount to a complete ethical
					victory. As Ihde (2002) suggests, improvements in format often require more
					specialised competencies from users. Just as written literature expanded access
					while creating a divide between literate and illiterate populations, a similar
					division persists in digital environments (Ong, 1982).
				</p>

				<p>
					In the case of digital literature, this divide becomes even more pronounced, as
					users require greater technical competence to engage with electronic works. As a
					result, literary media once again risk becoming concentrated in the hands of a few
					experts and institutions, often serving particular interests. In this respect,
					digital media reproduce under new conditions many of the ethical difficulties first
					introduced by writing.
				</p>

				<p>
					These considerations outline the broader digital landscape surrounding the
					preservation and transmission of content. The purpose here is not to exhaust their
					philosophical implications, but to identify their limits and derive from them the
					central ethical consequences for electronic literature.
				</p>

				<h3>Ethical Concerns of Digital Literature</h3>

				<p>
					The consideration of digital literary content introduces significant changes,
					particularly regarding the loss of physicality and temporality that characterised
					traditional literature. In its many forms, traditional literature reflected the
					culture and values of specific societies. It emerged as a medium for preserving
					primordial narratives whose contents reflected the value systems of their
					communities to such an extent that they were often considered sacred.
				</p>

				<p>
					Traditional works also preserved the marks of their historical periods. Careful
					analysis could reveal ties to particular places and traces of concrete temporal
					conditions, even in narratives set in anachronistic times. Digital literature,
					however, tends to dissolve these spatial and temporal specificities, and this
					carries substantial ethical implications.
				</p>

				<p>
					Unlike traditional works, which were deeply rooted in local cultures, electronic
					literature often draws from a globalised digital culture, significantly expanding
					its reach. Yet it cannot escape Sartre’s ethical question: what is the purpose of
					writing? Is there anything genuinely worth communicating? What system of values
					sustains what is communicated?
				</p>

				<p>
					The fundamental ethical question thus becomes this: what kind of value system does
					digital literature transmit? This question places us before one of literature’s
					oldest dilemmas: the tension between content moderation and censorship.
				</p>

				<p>
					As discussed earlier, responsibility for moderating content in traditional
					literature historically rested with local religious and political authorities.
					However, with the rise of electronic narratives, the sheer volume of content
					produced renders this task vastly more difficult. The proliferation of digital
					content severely limits the capacity of local authorities to oversee what is
					published or circulated in digital literature.
				</p>

				<p>
					At present, content moderation falls largely to private companies, yet the
					persistence of harmful content online demonstrates the insufficiency of these
					efforts. We remain far from achieving a healthy and ethical dissemination of
					literary content.
				</p>

				<p>
					Ensuring the integrity of literary content now requires the collective effort of
					all actors involved. Global institutions may play an important role by establishing
					general guidelines for digital works and technologies, much as international bodies
					now promote responsibility among those who design, deploy, and use digital systems.
				</p>

				<p>
					However, given the enormous quantity of personal data collected online, this task
					must prioritise privacy over security understood in absolute terms. Protecting
					privacy is essential to preventing abuse, identity theft, and surveillance.
				</p>

				<p>
					Transparency is equally fundamental: users must understand how their data are used,
					how algorithmic decisions are made, and what the consequences of interacting with
					digital technologies may be. These are among the values that ought to orient
					digital literature. Although awareness of these issues is a necessary first step,
					their implementation remains unfinished.
				</p>

				<p>
					Another ethical concern raised by digital literature affects authorship and reading
					practices. Just as writing introduced new roles—such as scribes and editors—that
					transformed authorship, digital works have also altered traditional literary
					practices. One notable development is the rise of collaborative production.
				</p>

				<p>
					The increasing complexity of digital works often requires greater collaboration,
					introducing ethical implications related to shared responsibility. In collaborative
					works, responsibility is distributed across multiple contributors, complicating the
					attribution of accountability. Traditionally, literature allowed responsibility to
					be attributed relatively easily to a single author; in digital works, it may extend
					across institutions and communities.
				</p>

				<p>
					Experience shows that when responsibility is diffused across an institution rather
					than borne by an individual, accountability becomes more difficult to enforce. This
					complicates efforts to ensure responsible authorship.
				</p>

				<p>
					Moreover, the rise of technologies such as AI-generated content intensifies these
					problems by affecting both creative production and fair research practices. The
					ethical implications of such technologies are still emerging, and it remains too
					early to diagnose their full consequences. Yet reflection on them is necessary if
					we are to anticipate possible solutions.
				</p>

				<p>
					These implications also extend to the reader’s side. Multimodality demands
					participation and familiarity, requiring a degree of technical competence to be
					effective. Whereas traditional reading relies on gradually acquired literacies,
					digital forms introduce new and less familiar literacies. The result is a
					significant digital literacy gap.
				</p>

				<p>
					Although the traditional literacy gap persists, especially in regions with lower
					literacy rates, the digital divide is even more concerning. This gap widens
					further when accessibility for people with disabilities is considered. Inclusion is
					widely acknowledged as a value, yet it often remains more theoretical than
					practical.
				</p>

				<p>
					These are some of the central ethical issues associated with digital literature.
					Unlike aesthetic forms, whose development has intensified and expanded the
					capacities of traditional works, the moral landscape appears instead to have
					intensified longstanding problems. Though the ethical terrain remains obscure,
					recognising its challenges is essential for diagnosing and addressing possible
					solutions.
				</p>

				<p>
					Reality shows that form alone cannot be considered a victory for literature if its
					ethical dimension is neglected. The digital revolution has intensified moral
					challenges and demonstrated that technological progress does not in itself ensure
					ethical practice. History shows that goodwill is not always present, and often in
					short supply. Yet ethical reflection in literary practice has also made forms of
					progress possible.
				</p>

				<h3>Conclusion</h3>

				<p>
					In this study, we have demonstrated the importance of literature in the creation
					and transmission of culture. The emergence of culture is what distinguishes our
					species, <em>Homo sapiens</em>, from its predecessors. Beyond using the mind as a
					tool for survival, human beings created a spiritual dimension capable of giving the
					world meaning.
				</p>

				<p>
					From that moment onward, human efforts were directed toward finding ways to
					preserve and transmit this knowledge to future generations. Literature was the
					first medium to fulfil this task through oral narrative. Yet however powerful, oral
					tradition depended on language and memory, both subject to limitation. Humanity
					therefore sought more effective means of preservation and transmission.
				</p>

				<p>
					The emergence of writing marked a decisive moment in this process, allowing greater
					attention to be directed toward transmitted content rather than the preservation of
					form alone. Books and linear narrative facilitated scholarly work and enabled the
					proliferation and specialisation of knowledge. Written literature represented an
					aesthetic revolution by shifting emphasis from preserving form toward enriching
					content.
				</p>

				<p>
					The rise of digital technologies has triggered a new revolution in literary
					aesthetics. This revolution does not merely refine form; it has introduced an
					entirely new domain within literature: electronic literature. This domain depends on
					computational processes and, in addition to improving preservation and transmission,
					introduces distinctive aesthetic features such as hypertext, multimodality, and
					agency.
				</p>

				<p>
					Yet while the sophistication of form constitutes a remarkable achievement, the
					essential purpose of literature remains the preservation of culture and human
					knowledge, something inseparable from a strong ethical foundation. Literary
					progress is only meaningful when accompanied by responsible ethical practice.
				</p>

				<p>
					Challenges such as moderation, censorship, responsible creation, and
					accountability—present since the origins of literature—persist and intensify in
					digital contexts. For this reason, it is urgent to reflect upon and implement
					practices capable of addressing them.
				</p>

				<p>
					Recognising these limits is essential and returns us to literature’s fundamental
					purpose. Just as our ancestors overcame technical constraints to transmit this
					cultural treasure to us, we too must assume the ethical responsibility of
					preserving and transmitting the values that will sustain our species.
				</p>

				<p>
					Only if we meet these challenges may we honour the meaning of the existence
					bequeathed to us. May our descendants inherit this treasure and recognise
					themselves within the continuum of human knowledge. May they one day, in whatever
					cybernetic civilisation they inhabit, proudly declare themselves descendants of
					<em>Homo sapiens sapiens</em>.
				</p>
