			<article class="article-body">
				<h2>Capítulo IV</h2>
				<h3>Ética de la literatura digital</h3>

				<h3>Conservación y transmisión en un mundo orientado por datos</h3>

				<p>
					La ética, como muchas cuestiones filosóficas, suele atravesar múltiples disciplinas.
					Por ello, antes de avanzar, es necesario definir la perspectiva desde la cual serán
					abordados los temas. En esta investigación ya hemos establecido el marco en el que
					se sitúan las discusiones éticas. Comenzamos explorando la relación entre ética y
					estética en la literatura, subrayando cómo la forma y el contenido literarios se
					influyen mutuamente.
				</p>

				<p>
					La aparición de la literatura escrita introdujo consideraciones éticas decisivas,
					que sentaron las bases de los problemas que ahora abordamos. A partir del paralelismo
					entre la revolución escrita y la revolución digital, examinaremos las implicaciones
					éticas de la transformación digital en la literatura, centrándonos en las cuestiones
					centrales tratadas anteriormente y explorando cómo se manifiestan en el contexto
					digital.
				</p>

				<p>
					Conviene recordar que el objetivo primordial de los medios literarios es facilitar
					la conservación y transmisión de la cultura humana. Desde esta premisa, la primera
					tarea consiste en analizar cómo estos fines se ven afectados en el contexto digital.
					La digitalización ofrece un nuevo ámbito en el que los bienes literarios pueden
					preservarse de forma más eficaz que en los medios físicos. En este sentido, la
					literatura electrónica mejora la forma y favorece la conservación del contenido.
				</p>

				<p>
					Esta mejora se extiende también a la transmisión de la literatura. La aparición de
					internet ha contribuido a lo que suele llamarse un “mundo reducido”, en el que los
					bienes digitales pueden ser accesibles desde cualquier lugar con conexión, alcanzando
					niveles inéditos de disponibilidad.
				</p>

				<p>
					En consecuencia, la creación de recursos digitales se orienta por los principios
					FAIR: localizables, accesibles, interoperables y reutilizables (Wilkinson et al.,
					2016). Sin embargo, el desafío ético no consiste únicamente en promover estos
					principios, sino en garantizar que se apliquen efectivamente al interactuar con los
					actores implicados y con el público general.
				</p>

				<p>
					Aquí emergen las primeras preocupaciones éticas. En relación con la preservación, la
					pregunta inicial es qué se conserva exactamente en los bienes digitales. En segundo
					lugar, la ética exige que el contenido transmitido sea accesible y distribuido de
					manera justa entre todas las personas.
				</p>

				<p>
					Una preocupación significativa para la filosofía de las tecnologías digitales es cómo
					las tecnologías emergentes inciden en el diseño del mundo en su conjunto. En el
					capítulo anterior examinamos cómo los límites computacionales constriñen en última
					instancia la sofisticación de la forma y de rasgos como la interactividad y la
					agencia. La literatura electrónica se sitúa, en particular, dentro del contexto más
					amplio de un mundo orientado por datos.
				</p>

				<p>
					Ernst Jünger (1989) sostiene que las tecnologías digitales estructuran el mundo
					digital como un conjunto de datos, mientras que la respuesta humana funciona como un
					procesador que integra estos elementos. Al explorar esta fusión entre lo digital y lo
					real, Vincent Blok (2017, 45) afirma que “en la era digital no nos encontramos tanto
					con invenciones singulares como el telescopio, sino con un conjunto de tecnologías
					interconectadas e interdependientes, como sensores para recopilar datos,
					procesamiento de datos y ecosistemas tecnológicos interconectados”.
				</p>

				<p>
					Esta perspectiva subraya que la digitalización conduce a la datificación del mundo.
					Wheeler (2002) sostiene que el supuesto central de la física digital es que el
					universo está compuesto por bits de datos, sugiriendo que toda entidad física deriva
					de bits. Esta idea se alinea con el principio empirista de que el mundo es medible,
					y la medición digital queda reducida a unidades de datos. En consecuencia, nuevas
					normas y patrones se derivan de esos datos, perpetuando ciclos de sesgo y
					reduccionismo basados en sus propios supuestos.
				</p>

				<p>
					Como resultado, las obras digitales corren el riesgo de perder progresivamente sus
					propiedades cualitativas. Tecnologías recientes como la inteligencia artificial, la
					realidad aumentada y la realidad virtual ofrecen niveles inéditos de simulación e
					inmersión, pero permanecen ancladas en un mundo orientado por datos.
				</p>

				<p>
					Aunque conviene reconocer sus capacidades avanzadas, también es crucial advertir que
					estas realidades digitales están previamente seleccionadas y filtradas. Este proceso
					reconfigura categorías humanas fundamentales, como la espacialidad y la temporalidad,
					a medida que nuestras experiencias dependen cada vez menos de la ubicación física y
					la proximidad.
				</p>

				<p>
					Al hablar de accesibilidad, también es necesario considerar sus límites. El potencial
					aparentemente ilimitado de los bienes digitales no equivale a una victoria ética
					completa. Como sugiere Ihde (2002), la mejora del formato suele exigir competencias
					más especializadas por parte de los usuarios. Del mismo modo que la aparición de la
					literatura escrita amplió el acceso a las obras, también abrió una brecha entre
					personas alfabetizadas y no alfabetizadas, una distancia que persiste hasta hoy
					(Ong, 1982).
				</p>

				<p>
					El caso de la literatura digital es aún más pronunciado, pues los usuarios requieren
					mayor experiencia técnica para interactuar con las obras electrónicas. En
					consecuencia, los medios literarios vuelven a concentrarse en manos de unos pocos
					expertos e instituciones, con el riesgo de servir a intereses particulares. Esta
					situación reproduce, bajo nuevas condiciones, los desafíos éticos que la literatura
					afrontó con el surgimiento de la escritura.
				</p>

				<p>
					Estas consideraciones delimitan el paisaje digital más amplio en torno a la
					conservación y transmisión del contenido. Nuestro propósito no es agotar sus
					implicaciones filosóficas, sino identificar sus límites y derivar de ellos las
					principales consecuencias éticas para la literatura electrónica.
				</p>

				<h3>Preocupaciones éticas de la literatura digital</h3>

				<p>
					La consideración del contenido literario digital introduce cambios significativos,
					en especial respecto a la pérdida de fisicalidad y temporalidad que caracterizaba a
					la literatura tradicional. Esta, en sus diversas formas, reflejaba la cultura y los
					valores de sociedades específicas. Surgió como medio para conservar narraciones
					primordiales, cuyos contenidos reflejaban los sistemas de valores de su comunidad
					hasta el punto de ser considerados sagrados.
				</p>

				<p>
					Las obras tradicionales también conservaban las marcas de sus períodos históricos.
					Un análisis atento podía revelar vínculos con lugares determinados y huellas
					temporales concretas, incluso en narraciones situadas en épocas anacrónicas. Sin
					embargo, la literatura digital tiende a difuminar estas especificidades espaciales
					y temporales, lo que conlleva importantes implicaciones éticas.
				</p>

				<p>
					A diferencia de las obras tradicionales, profundamente arraigadas en culturas
					locales, la literatura electrónica suele nutrirse de una cultura digital globalizada,
					ampliando considerablemente su alcance. Pese a ello, no puede escapar a la pregunta
					ética planteada por Sartre: ¿cuál es el propósito de escribir?, ¿hay algo que
					realmente merezca ser comunicado?, ¿qué sistema de valores sostiene aquello que se
					comunica?
				</p>

				<p>
					La cuestión ética fundamental se convierte entonces en esta: ¿qué tipo de sistema de
					valores transmite la literatura digital? Esta pregunta nos sitúa frente a uno de los
					dilemas más antiguos de la literatura: la tensión entre moderación del contenido y
					censura.
				</p>

				<p>
					Como se expuso anteriormente, la responsabilidad de moderar el contenido en la
					literatura tradicional recaía históricamente sobre autoridades religiosas y políticas
					locales. Sin embargo, con el surgimiento de las narrativas electrónicas, el volumen
					masivo de contenido producido complica enormemente esa tarea. La proliferación del
					contenido digital limita la capacidad de las autoridades locales para supervisar de
					manera efectiva aquello que se publica o exhibe en la literatura digital.
				</p>

				<p>
					Actualmente, la moderación del contenido recae en gran medida sobre empresas
					privadas, pero la persistencia de contenidos dañinos en internet demuestra la
					insuficiencia de estos esfuerzos. Aún estamos lejos de alcanzar una diseminación
					saludable y ética del contenido literario.
				</p>

				<p>
					Garantizar la integridad del contenido literario exige ahora el esfuerzo colectivo
					de todos los actores implicados. Las autoridades globales pueden desempeñar un papel
					importante estableciendo directrices generales para las obras y tecnologías
					digitales, tal como hacen organismos internacionales al promover la responsabilidad
					de quienes diseñan, despliegan y utilizan tecnologías digitales.
				</p>

				<p>
					No obstante, dada la enorme cantidad de datos personales recopilados en línea, esta
					tarea debe priorizar la privacidad por encima de la seguridad entendida de forma
					absoluta. Proteger la privacidad resulta esencial para evitar abusos, robo de
					identidad y vigilancia.
				</p>

				<p>
					La transparencia también es fundamental: los usuarios necesitan comprender cómo se
					utilizan sus datos, cómo se toman decisiones algorítmicas y cuáles son las
					implicaciones de interactuar con tecnologías digitales. Estos son algunos de los
					valores que deberían orientar la literatura digital. Aunque la concienciación sobre
					estas cuestiones constituye un primer paso necesario, promover y sostener dichos
					valores sigue siendo una tarea pendiente.
				</p>

				<p>
					Otra preocupación ética planteada por la literatura digital afecta a la autoría y a
					las prácticas de lectura. Así como la escritura introdujo nuevos roles —como
					escribas y editores— que transformaron la autoría, las obras digitales han alterado
					también las prácticas literarias tradicionales. Un desarrollo notable es el auge de
					las prácticas colaborativas.
				</p>

				<p>
					La complejidad creciente de las obras digitales suele exigir mayor colaboración, lo
					que introduce implicaciones éticas relacionadas con la responsabilidad compartida.
					En las obras colaborativas, la responsabilidad se distribuye entre múltiples
					contribuyentes, complicando la atribución de responsabilidad. Tradicionalmente, la
					literatura permitía atribuir con relativa facilidad la responsabilidad a un único
					autor; en cambio, en las obras digitales, esta puede extenderse a instituciones y
					comunidades más amplias.
				</p>

				<p>
					La experiencia muestra que, cuando la responsabilidad se difumina dentro de una
					institución en lugar de recaer en un individuo, resulta más difícil hacerla
					exigible. Esta dificultad complica los esfuerzos por garantizar una autoría
					responsable.
				</p>

				<p>
					Además, el auge de tecnologías como el contenido generado por inteligencia
					artificial intensifica estos problemas, al afectar tanto al proceso creativo como a
					las prácticas justas de investigación. Las implicaciones éticas de estas tecnologías
					continúan emergiendo, por lo que aún es pronto para diagnosticar por completo sus
					desafíos. Sin embargo, reflexionar sobre ellos resulta indispensable para anticipar
					posibles soluciones.
				</p>

				<p>
					Estas implicaciones se extienden también al lado del lector. La multimodalidad exige
					participación y experiencia, y requiere cierto grado de dominio técnico para ser
					efectiva. Mientras que la lectura tradicional se apoya en alfabetizaciones adquiridas
					gradualmente, lo digital introduce alfabetizaciones nuevas y menos familiares. De
					ello resulta una brecha significativa de alfabetización digital.
				</p>

				<p>
					Aunque la brecha literaria tradicional persiste, especialmente en regiones con menor
					nivel de alfabetización, la brecha digital resulta aún más preocupante. Esta
					distancia se amplía cuando se considera la accesibilidad para personas con
					discapacidad. Aunque la inclusión es un valor ampliamente reconocido, en muchas
					ocasiones permanece más en el plano teórico que en la práctica.
				</p>

				<p>
					Estos son algunos de los problemas éticos centrales asociados con la literatura
					digital. A diferencia de las formas estéticas, cuya evolución ha potenciado rasgos
					frente a las obras tradicionales, el paisaje moral parece haber intensificado
					problemas fundamentales. Aunque el terreno ético resulte todavía oscuro, reconocer
					sus desafíos es esencial para diagnosticar y abordar posibles soluciones.
				</p>

				<p>
					La realidad muestra que la forma por sí sola no puede considerarse una victoria para
					la literatura si se desatiende la dimensión ética. La revolución digital ha
					exacerbado desafíos morales y ha revelado que el progreso tecnológico no garantiza
					por sí mismo una práctica ética. La historia demuestra que la buena voluntad no
					siempre está presente, y con frecuencia escasea. Sin embargo, la reflexión ética en
					las prácticas literarias ha impulsado también formas de progreso.
				</p>

				<h3>Conclusión</h3>

				<p>
					En este estudio hemos mostrado la importancia de la literatura en la creación y
					transmisión de la cultura. La emergencia de la cultura es aquello que distingue a
					nuestra especie, <em>Homo sapiens</em>, de sus predecesores. Más allá de emplear la
					mente como herramienta de supervivencia, los seres humanos crearon una dimensión
					espiritual capaz de dotar al mundo de significado.
				</p>

				<p>
					Desde entonces, los esfuerzos humanos se orientaron a encontrar medios para preservar
					y transmitir ese conocimiento a las generaciones futuras. La literatura fue el primer
					medio en cumplir este fin mediante relatos orales. Pero, aunque poderosa, la tradición
					oral dependía del lenguaje y la memoria, ambos sujetos a limitaciones. Por ello, la
					humanidad buscó métodos más eficaces de preservación y transmisión.
				</p>

				<p>
					La aparición de la escritura marcó un hito en este proceso, permitiendo concentrar
					más la atención en el contenido transmitido que en la conservación de la forma. El
					libro y la narración lineal facilitaron el trabajo académico y propiciaron la
					proliferación y especialización del conocimiento. La literatura escrita representó
					una revolución estética al desplazar el énfasis desde la preservación de la forma
					hacia el enriquecimiento del contenido.
				</p>

				<p>
					La irrupción de las tecnologías digitales ha desencadenado una nueva revolución en
					la estética literaria. Esta revolución no se limita a sofisticar la forma, sino que
					ha introducido un nuevo dominio dentro de la literatura: la literatura electrónica.
					Este ámbito depende de procesos computacionales y, además de mejorar la preservación
					y transmisión, incorpora rasgos estéticos excepcionales como el hipertexto, la
					multimodalidad y la agencia.
				</p>

				<p>
					Sin embargo, aunque la sofisticación de la forma constituye un logro notable, el
					propósito esencial de la literatura sigue siendo preservar la cultura y el
					conocimiento humano, algo inseparable de una base ética sólida. El progreso literario
					solo resulta significativo cuando va acompañado de prácticas éticas responsables.
				</p>

				<p>
					Desafíos como la moderación, la censura, la creación responsable y la rendición de
					cuentas —presentes desde los orígenes de la literatura— persisten e incluso se
					intensifican en el contexto digital. Por ello, resulta urgente reflexionar e
					implementar prácticas capaces de afrontar estas cuestiones.
				</p>

				<p>
					Reconocer estas limitaciones es fundamental y nos devuelve al propósito esencial de
					la literatura. Así como nuestros antepasados sortearon restricciones técnicas para
					transmitirnos este tesoro cultural, también nosotros debemos asumir la responsabilidad
					ética de preservar y transmitir los valores que sostendrán nuestra especie.
				</p>

				<p>
					Solo si logramos afrontar estos desafíos podremos honrar el sentido de la existencia
					que nos fue legado. Que nuestros descendientes hereden este tesoro y se reconozcan en
					el continuo del conocimiento humano. Que algún día, en cualquier civilización
					cibernética en la que habiten, puedan declararse con orgullo descendientes de
					<em>Homo sapiens sapiens</em>.
				</p>
