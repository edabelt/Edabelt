				<h2>La literatura en un contexto digital</h2>

				<p>
					Comprender el contexto amplio en el que emerge un fenómeno es esencial para captar
					sus contornos más definitorios, especialmente en el caso de los medios literarios
					digitales. Ignorar esta condición conduce a lo que James O’Sullivan denomina
					“miopía”: una forma de segregación crítica en la que las prácticas se desligan de
					los contextos que las han modelado (O’Sullivan, 2019, 1). Esta consideración
					resulta crucial al examinar la historia de los medios, donde las formas nuevas no
					surgen de manera aislada, sino profundamente entrelazadas con sus predecesoras.
				</p>

				<p>
					La relación entre medios emergentes y medios establecidos es tan estrecha que
					algunos estudiosos han llegado a sostener que debemos “reconocer la falacia de los
					nuevos medios”, entendiendo que la aparición de nuevas formas no es más que una fase
					dentro de un ciclo cultural continuo (O’Sullivan, 2019, 4).
				</p>

				<p>
					Sin embargo, explorar estas relaciones exige una aproximación matizada. Situar un
					medio en su marco histórico solo permite captar parcialmente su esencia,
					especialmente cuando se lo compara con formas anteriores. Es necesario examinar con
					cuidado cómo el entorno digital más amplio informa las características singulares de
					la literatura electrónica. Como sugiere O’Sullivan: “Definir la e-lit como una mera
					yuxtaposición entre lo viejo y lo nuevo es una simplificación grosera. ¿Cómo
					podríamos concebir el producto de esta conexión sin comprender ni ‘lo viejo’ ni ‘lo
					nuevo’ en sí mismos?” (O’Sullivan, 2019, 26).
				</p>

				<p>
					¿Cuál es, entonces, la conexión entre el surgimiento de la literatura escrita y el
					de la literatura digital? Antes de abordar esta cuestión, conviene señalar que dicho
					vínculo constituye, en primer lugar, una construcción analítica orientada por el
					alcance y los temas de esta investigación. En términos filosóficos, se trata de una
					conexión de orden epistémico —relativa a cómo conocemos y comprendemos— antes que
					ontológico, es decir, relativa al ser mismo.
				</p>

				<p>
					La transición hacia formatos escritos y digitales puede entenderse como parte de un
					mismo ciclo de transformación mediática. Ambos responden a patrones similares: cada
					uno representa una alteración sustancial del formato que afecta de manera decisiva
					los objetivos primarios de los medios, a saber, la producción, conservación y
					diseminación de la cultura.
				</p>

				<p>
					Tras la invención de la escritura, las narraciones orales migraron por completo al
					formato escrito. Un desplazamiento semejante ocurre hoy, en el paso de los soportes
					físicos al entorno digital. Este proceso de transformación ha generado profundas
					consecuencias estéticas y éticas. Los conceptos fundamentales desarrollados en la
					tradición literaria sirven aquí como puente para comprender el tránsito entre la
					literatura tradicional y la literatura digital.
				</p>

				<p>
					Desde una perspectiva más amplia, la escritura propició tanto la proliferación como
					la segmentación del conocimiento. Aquello que en un inicio se hallaba contenido en
					las narraciones orales comenzó a diversificarse en disciplinas emergentes como la
					filosofía y la ciencia. La era digital, sin embargo, no solo ha producido nuevas
					disciplinas —como las humanidades digitales—, sino que ha reabierto la posibilidad
					de reintegración y colaboración entre campos antes escindidos.
				</p>

				<p>
					Lo que distingue al presente digital es precisamente su capacidad de recomponer
					puentes entre ciencias y humanidades, favoreciendo nuevas formas de colaboración,
					preservación y circulación del conocimiento. Este es, quizá, uno de los impactos más
					significativos del contexto digital.
				</p>

				<p>
					No obstante, la historia de los medios muestra que todo progreso implica también un
					coste. El precio más inmediato de toda revolución es la confusión que introduce:
					nuevos territorios exigen exploración, pero también alteran la comprensión de aquello
					que ya conocíamos. Así como la invención de la escritura obligó a Aristóteles a
					iniciar la primera gran reflexión estética sobre la literatura, la irrupción de los
					formatos digitales exige hoy una nueva revisión crítica de sus formas, límites y
					consecuencias.
				</p>

                <h2>Estética de la literatura digital</h2>

<h3>Rasgos estéticos de la literatura digital</h3>

<p>
	Confinada al libro, la literatura permaneció durante siglos limitada por la linealidad del
	texto como estructura narrativa dominante, y esta linealidad condicionó el desarrollo mismo
	de la trama. En consecuencia, la experiencia estética quedó determinada casi exclusivamente
	por el acto de leer. La literatura escrita despojó a la narración de gran parte de la
	multimodalidad presente en las antiguas epopeyas, donde la música y la voz del poeta
	añadían otras dimensiones sensoriales, aunque todavía rudimentarias. Sin embargo, la
	invención de la web a finales de la década de 1990 inauguró una transformación profunda. La
	aparición del hipertexto y la integración del texto con múltiples medios devolvieron a la
	literatura una multimodalidad largamente relegada. Esta fusión enriqueció la narración,
	ofreciendo nuevas formas de construir relatos y generando capas más hondas de interacción y
	compromiso estético. Así como la invención de la escritura dio lugar a la literatura
	escrita, las innovaciones introducidas por la web y las tecnologías digitales abrieron el
	camino hacia un nuevo dominio literario: la literatura electrónica.
</p>

<p>
	La literatura electrónica es un término técnico que designa de manera específica aquellos
	géneros nacidos en el entorno digital, y no simplemente obras tradicionales mostradas en
	dispositivos electrónicos. Se trata de una forma de literatura que depende de la
	computadora no solo para su distribución, sino para su propia constitución. El primer género
	nacido digitalmente fue la hiperficción, surgida en la década de 1980 (Hayles, 2008,
	13-14). La hiperficción consiste en relatos no lineales en los que el texto enlazado
	permite al lector recorrer distintos caminos narrativos, conduciendo a múltiples desenlaces
	según sus elecciones. Ejemplos notables de este género son <em>Afternoon</em>, de Michael
	Joyce, y <em>Patchwork Girl</em>, de Shelley Jackson.
</p>

<p>
	Los avances tecnológicos posteriores enriquecieron aún más esta multimodalidad, permitiendo
	que la literatura electrónica integrara texto con elementos visuales y auditivos de forma
	orgánica. Esta convergencia de medios —imágenes, sonidos y animaciones— intensifica la
	experiencia narrativa y sumerge al lector en capas más densas de significación. En la
	combinación de imágenes y texto, ilustraciones, fotografías y vídeos ofrecen contexto,
	evocan emociones y expanden las posibilidades del relato. <em>Patchwork Girl</em>, por
	ejemplo, entrelaza imágenes y texto de manera no lineal, produciendo una narración
	fragmentaria pero cohesionada que el lector debe recomponer activamente.
</p>

<p>
	Los elementos auditivos, como música de fondo, efectos sonoros y voces, añaden otra
	dimensión a la experiencia de lectura. Estos componentes modelan la atmósfera y orientan la
	interpretación, como puede observarse en <em>Deviant: The Possession of Christian Shaw</em>,
	de Donna Leishman, donde una banda sonora inquietante intensifica el tono espectral del
	relato. Del mismo modo, la animación puede insuflar movimiento a la narración, ilustrando
	acciones, encarnando conceptos abstractos o simplemente introduciendo dinamismo.
	<em>RedRidingHood</em>, también de Leishman, es un ejemplo paradigmático: sus animaciones
	interactivas responden a las elecciones del lector y combinan narración tradicional con
	imágenes animadas para producir una experiencia más inmersiva.
</p>

<p>
	Además de reconfigurar la linealidad y restaurar la multimodalidad, la literatura
	electrónica introdujo otra innovación decisiva: la interactividad. Este avance permitió al
	lector participar activamente en la narración, generando entradas que afectan directamente
	el curso del relato. El auge de la ficción interactiva en la década de 1980 —también
	conocida como aventuras de texto— ejemplifica este giro. El lector dejó de consumir
	pasivamente una historia para intervenir en ella mediante comandos que controlaban
	personajes y alteraban el desarrollo de la trama, abriendo rutas diversas y múltiples
	finales. Ejemplos clásicos como <em>Zork</em>, de Infocom, y <em>A Mind Forever
	Voyaging</em>, de Steve Meretzky, muestran cómo enlaces, mapas y elementos multimedia
	transformaron la lectura en una experiencia dinámica y participativa.
</p>

<p>
	Estas innovaciones no se limitaron a los géneros narrativos, sino que alcanzaron también a
	la poesía, dando lugar a la poesía digital en la década de 1990. Los poetas comenzaron a
	explorar el medio digital integrando texto, imagen, sonido, animación e interactividad para
	expandir los límites de la expresión poética tradicional (Hayles, 2008, 53). Esta
	integración de elementos multimedia permitió la creación de obras que desafían y enriquecen
	las convenciones del lenguaje poético.
</p>

<p>
	Otro género que emergió en la década de 1990 fue la ficción en Flash. Utilizando Adobe
	Flash (antes Macromedia Flash), esta forma de literatura electrónica creó relatos
	multimedia que combinaban texto, imagen, sonido e interactividad. Entre sus ejemplos más
	notables se encuentran <em>RedRidingHood</em>, de Donna Leishman, y <em>The Dazzle as
	Question</em>, de Young-Hae Chang Heavy Industries.
</p>

<p>
	La mejora en la accesibilidad a internet y el aumento del ancho de banda a finales de los
	años noventa y comienzos de los dos mil hicieron posible la aparición de la ficción en red.
	Este género aprovecha internet como medio narrativo e incorpora escritura colaborativa,
	participación del lector e influencias en tiempo real. Ejemplos destacados son
	<em>Lexia to Perplexia</em>, de Talan Memmott, y <em>Dakota</em>, de Young-Hae Chang Heavy
	Industries.
</p>

<p>
	Los intentos por integrar recursos digitales en el teatro condujeron al desarrollo del
	drama interactivo a comienzos de los años dos mil. Este género fusiona teatro, cine y
	videojuego para crear experiencias narrativas inmersivas. Los participantes interactúan con
	personajes e influyen en el desarrollo de la historia. Entre sus ejemplos más conocidos se
	encuentran <em>Façade</em>, de Michael Mateas y Andrew Stern, y <em>The Last Express</em>,
	de Jordan Mechner.
</p>

<p>
	La revolución digital en la literatura electrónica no solo transformó la forma de las obras
	—introduciendo no linealidad, multimodalidad y participación activa del lector—, sino que
	también cuestionó las nociones tradicionales de autoría. En este contexto, los esfuerzos
	colaborativos e interdisciplinarios dieron lugar a nuevos géneros, como las narrativas
	colaborativas y colectivas. Las plataformas digitales facilitaron formas de escritura en las
	que múltiples autores, e incluso lectores, pueden intervenir en el desarrollo de una obra.
	Comunidades y herramientas como <em>Twine</em> ejemplifican esta tendencia, permitiendo a
	los usuarios crear, compartir y expandir historias interactivas. Este enfoque disuelve las
	fronteras tradicionales entre autor y lector, favoreciendo una forma más democrática e
	inclusiva de producción narrativa.
</p>

<p>
	En el nuevo milenio, la evolución de las formas mediáticas se ha acelerado aún más, y
	tecnologías emergentes como la realidad aumentada (AR) y la realidad virtual (VR) anuncian
	la posible apertura de nuevos territorios literarios. Aunque todavía es pronto para evaluar
	plenamente su impacto, estas tecnologías ya han comenzado a dar lugar a géneros
	innovadores.
</p>

<p>
	La literatura en realidad aumentada (AR), surgida en la década de 2010, utiliza esta
	tecnología para superponer contenido digital sobre el mundo físico, creando experiencias
	narrativas inmersivas e interactivas. Ejemplos de ello son <em>Miranda</em>, de Will Self,
	y <em>The Ghosts of the Past</em>, de ARTE.
</p>

<p>
	La literatura en realidad virtual (VR), también desarrollada en la década de 2010, ofrece
	entornos narrativos tridimensionales y plenamente inmersivos mediante tecnología VR,
	permitiendo al lector experimentar la historia desde dentro. Ejemplos representativos de
	este género son <em>Wolves in the Walls</em>, de Fable Studio, y <em>The Key</em>, de
	Celine Tricart.
</p>

<p>
	La narrativa transmedia, otro género característico de la década de 2010, extiende los
	relatos a través de múltiples plataformas y medios. Esta estrategia permite experimentar una
	historia mediante libros, sitios web, videojuegos y redes sociales. Ejemplos de esta forma
	son la serie <em>The 39 Clues</em> y <em>Inanimate Alice</em>, de Kate Pullinger y Chris
	Joseph.
</p>

<p>
	Entre las tecnologías emergentes, la inteligencia artificial destaca de manera especial, al
	dar lugar al desarrollo de literatura impulsada por IA en la década de 2020. Este género
	utiliza sistemas de inteligencia artificial para generar y adaptar narrativas en tiempo
	real, ofreciendo experiencias de lectura personalizadas según la interacción y las entradas
	del lector. Ejemplos notables de esta tendencia son <em>AI Dungeon</em>, de Nick Walton, y
	<em>Project December</em>, de Jason Rohrer.
</p>

<p>
	Estos géneros ilustran la evolución de la literatura electrónica desde la hiperficción
	elemental hasta experiencias complejas e inmersivas que integran diversas formas de medios y
	tecnología. Cada uno de ellos expande los límites de la narración tradicional y ofrece
	nuevas maneras de interactuar con el relato y de modelar su devenir.
</p>
