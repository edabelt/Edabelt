				<h2>Prolegómenos</h2>

				<p>
					Para comprender con profundidad un fenómeno, es necesario recurrir a una
					metodología filosófica rigurosa que permita identificar las condiciones que hacen
					posible su existencia. Como sostiene Aristóteles en los
					<em>Analíticos posteriores</em> (Aristóteles, 1984a, Libro I, Capítulo 2), el
					conocimiento verdaderamente científico exige comprender las causas que subyacen a
					todo fenómeno. Esta idea es desarrollada con mayor amplitud en la
					<em>Metafísica</em>, donde expone cuatro causas que definen la esencia de toda
					realidad: la causa material (aquello de lo que algo está hecho), la causa formal
					(su forma o esencia), la causa eficiente (el agente principal de cambio o
					permanencia) y la causa final (su propósito último u objetivo) (Aristóteles,
					1984b, Libro I, Capítulo 3).
				</p>

				<p>
					La referencia al filósofo griego no es accidental; como se mostrará, el método de
					indagación aristotélico resulta particularmente esclarecedor cuando se aplica a la
					ética y la estética de la literatura electrónica. Trazar paralelos entre la teoría
					de la causalidad de Aristóteles y la obra literaria permite desentrañar los
					elementos que configuran las prácticas mediáticas, categoría más amplia en la que
					se inscribe la literatura. En efecto, “la cuestión de la relación entre forma y
					contenido se encuentra en las raíces más antiguas de las humanidades”
					(O’Sullivan, 2016, 386). Del mismo modo, la exploración seminal de Aristóteles
					sobre la literatura en la <em>Poética</em> ofrece un marco privilegiado para la
					investigación estética. Es allí donde aplica por primera vez el binomio materia y
					forma a un examen sistemático de la obra literaria.
				</p>

				<p>
					Así, la teoría aristotélica de la causalidad constituye el marco fundamental de
					esta investigación, pues la naturaleza de las causas se corresponde tanto con la
					dimensión estética como con la ética. Considerar, por ejemplo, los materiales
					(causa material) con los que se compone un formato literario y la forma en que el
					texto se dispone (causa formal) supone adentrarse en la estética de la forma. En
					cambio, atender a la causa final del contenido —como puede ser la educación moral—
					y a sus implicaciones nos sitúa de lleno en el terreno de la ética.
				</p>

				<p>
					La primera fase de esta investigación consistirá en remontarse a los orígenes de la
					literatura para comprender sus procesos fundamentales. A través de ese recorrido se
					buscará esclarecer los conceptos centrales de la estética y la ética literarias.
					Dado el alcance de la tarea, nos concentraremos en aquellas ideas decisivas que
					permitan comprender de qué modo la literatura electrónica ha transformado,
					estética y éticamente, la tradición literaria.
				</p>

				<p>
					En el plano estético, se describirá la constitución de la forma en su dimensión
					externa —el soporte y la disposición del texto— y en su dimensión interna —los
					elementos específicos y sus relaciones dentro del tejido textual que configuran un
					género literario—. Asimismo, se atenderá a la manera en que la obra se ofrece al
					espectador, al lector o al usuario: su dimensión sensorial, las emociones que
					suscita y el potencial transformador que habita en toda experiencia estética.
				</p>

				<p>
					En última instancia, en tanto fusión de forma y contenido, la literatura
					experimenta transformaciones recíprocas cuando uno de estos elementos se altera.
					Por ello, examinaremos de qué modo las mutaciones de la forma literaria han
					reconfigurado la naturaleza del contenido. Este examen revelará cuestiones éticas
					de primer orden: la accesibilidad e integridad de lo transmitido, la capacidad de
					la literatura para modelar conductas y decisiones, los problemas de moderación y
					censura, así como las preguntas que suscita la autoría.
				</p>

				<p>
					Estos conceptos fundamentales de la estética y la ética, nacidos con la propia
					literatura, siguen presentes hoy, aunque la literatura electrónica los reformule
					según sus propias condiciones. Comprender su naturaleza permitirá entender con
					mayor claridad de qué modo la literatura digital constituye una revolución
					estética y ética en la historia de la literatura.
				</p>

				<p>
					Desde esta perspectiva, es posible reconocer momentos decisivos en la historia
					literaria que revelan cómo el juego dinámico entre forma y materia ha guiado la
					evolución de la literatura hasta desembocar en la era contemporánea de lo digital.
					Puesto que el surgimiento de la literatura se halla íntimamente ligado al origen
					de la cultura (Cassirer, 1953-1957, 53), nuestro recorrido debe comenzar en los
					albores mismos de la civilización humana.
				</p>

                <h2>Capítulo I</h2>
<h3>Estética de la forma</h3>

<h3>Narrativa en la conservación y transmisión de la cultura</h3>

<p>
	Resulta difícil precisar el momento exacto en que surgieron las primeras expresiones
	literarias. Lo que sí parece evidente es que la literatura fue decisiva para el florecimiento
	de la cultura, al desarrollarse como expresión de aquello que Cassirer (1953-1957, 78)
	denominó pensamiento simbólico. Esta nueva dimensión hizo posible el nacimiento de la
	religión, del imaginario literario colectivo y de ese nuevo dominio que hoy reconocemos como
	cultura. Fue este poderoso logro el que hizo a nuestros antepasados dignos del nombre que
	aún conservan: <em>Homo sapiens</em>, los humanos que saben.
</p>

<p>
	Cuando los seres humanos se enfrentaron a condiciones hostiles y quedaron desconcertados ante
	los misterios de la existencia —entre ellos, la conciencia de la muerte—, esta dimensión
	espiritual ofreció consuelo y esperanza; en ella buscaron auxilio divino para otorgar sentido
	a sus vidas arduas y desentrañar los enigmas que envolvían al mundo en un misterio
	permanente.
</p>

<p>
	“Gilgamesh, que vio el abismo, los cimientos de la tierra,<br />
	todo lo comprendió por entero,<br />
	vio lo oculto y reveló lo secreto”. (<em>La epopeya de Gilgamesh</em>, I,5).
</p>

<p>
	A partir de entonces, una imaginación fecunda se desplegó en sus mentes, poblando el entorno
	de criaturas, dioses y creadores. Los dioses observaban el curso del mundo y gobernaban la
	totalidad de lo existente. Surgieron mitos de creación que explicaban cómo estos dioses
	forjaban y regían el cosmos, acompañados de danzas, objetos sagrados y rituales complejos que
	servían para explicar los fenómenos del mundo y encender una chispa de esperanza en quienes
	buscaban auxilio: “Alzo mis ojos a los montes: ¿de dónde vendrá mi ayuda?<br />
	Mi ayuda viene del Señor, creador del cielo y de la tierra.” (<em>Salmos</em> 121:1-2).
</p>

<p>
	La emergencia de una esfera cultural en la sociedad humana marcó, sin duda, el comienzo de una
	nueva era. La cultura se convirtió en la fuerza cohesiva que articuló la existencia humana,
	proporcionándole sentido, identidad, códigos morales, conocimiento abstracto y mucho más
	(Cassirer, 1955, 102). Convenció a los seres humanos de que el mayor peligro al que se
	enfrentaban podía ser vencido. Y aunque la muerte no pudiera ser derrotada, dejó de simbolizar
	un final definitivo para convertirse en el umbral hacia una vida inmortal.
</p>

<p>
	Estas comunidades sabían que poseían un recurso invaluable para orientarse en el camino de la
	vida. Preservar y transmitir ese tesoro a las generaciones futuras era esencial para la
	supervivencia de la especie. Dos elementos humanos resultaron decisivos en esta tarea: el
	lenguaje y la memoria. A través del lenguaje, los primeros pueblos elaboraron relatos
	fundacionales para explicar el mundo, dotar de sentido a sus vidas y estructurar valores
	morales y normas de conducta. Walter Benjamin (1968, 446) sostiene que “el arte de narrar,
	profundamente arraigado en la tradición oral, fomenta una forma comunitaria y experiencial de
	transmisión del saber esencial para la cultura”. Es la memoria humana la que permite conservar
	y transmitir estos relatos. “La memoria crea la cadena de la tradición que pasa de generación
	en generación. Inicia la trama que al final forman todas las historias juntas” (Benjamin,
	1968, 450). Con la práctica de la narración asistimos al nacimiento de la literatura, criatura
	aún nacida del oído.
</p>

<p>
	La literatura surgió inicialmente para conservar y transmitir el conocimiento cultural,
	cumpliendo así con su <em>telos</em> o finalidad. Su propósito principal consistía en
	transmitir la identidad de la comunidad e inculcar en los individuos valores morales y normas
	de conducta (Adams, 2007, 102). En sus primeras formas, la literatura fue eminentemente oral y
	dependía de la memoria como principal medio de almacenamiento y transmisión (Smith, 2001, 78).
	En las primeras etapas de la civilización, el volumen de mitos y saberes era aún limitado y
	podía ser contenido por unos pocos individuos excepcionales (Jones, 2010a, 102). Estos
	individuos dotados retenían y recitaban la tradición, dando origen a la primera gran figura de
	la literatura: el poeta (Johnson, 1995, 56).
</p>

<p>
	En la antigua Grecia, los rapsodas tenían la tarea de recitar las historias del imaginario
	colectivo de la comunidad (Brown, 2005a, 34). Otras figuras, como los <em>aoidoi</em>, eran
	responsables de componerlas (Miller, 2008a, 22). Las primeras expresiones literarias griegas
	fueron profundamente multimodales: incorporaban acompañamiento musical y estaban estructuradas
	en verso, lo que incrementaba su atractivo ante el público (Williams, 2012, 89). Estas
	narraciones se centraban principalmente en las gestas épicas de héroes locales, cuyas vidas
	funcionaban como modelos morales dignos de imitación (Robinson, 2018a, 112). Esta rica
	tradición narrativa sentó las bases para la aparición de la épica como primer gran género
	literario.
</p>

<p>
	Conviene subrayar que el contenido transmitido era considerado sagrado. En consecuencia, la
	creatividad del compositor se concentraba principalmente en la forma, mientras que la sustancia
	se entendía como revelada o dictada por una musa. Esta atribución divina impregnó la
	transmisión literaria de una dimensión ética intrínseca, enlazando ética y estética en la
	literatura (Davis, 2016a, 78). Los esfuerzos se dirigieron entonces al desarrollo de nuevos
	formatos capaces de combatir la corrupción y mejorar la durabilidad y legibilidad.
</p>

<p>
	Las principales dificultades surgían de la propia naturaleza del lenguaje y de la memoria, que,
	aunque poderosos, son también medios profundamente imperfectos. Por un lado, hacen posible la
	creación de tradiciones narrativas; por otro, imponen limitaciones como soportes de
	transmisión (Jones, 2010b, 45). A medida que la población crecía y las tradiciones se
	multiplicaban, el volumen de información comenzó a superar la capacidad de la memoria
	colectiva (Brown, 2005b, 112). Además, el lenguaje rara vez logra capturar plenamente los
	matices de los acontecimientos, dando lugar a múltiples variaciones a partir de una misma
	fuente (Miller, 2008b, 89). La experiencia de la vida desborda con frecuencia tanto la
	memoria como el lenguaje, que no son más que dimensiones parciales de la experiencia humana.
	En rigor, dedicamos más tiempo a vivir que a narrar o recordar. Por ello, se hicieron
	necesarios medios de transmisión más eficaces (Robinson, 2018b, 34), especialmente para
	superar las limitaciones de la memoria y refinar la precisión del lenguaje (Davis, 2016b, 56).
	Fortunadamente, una invención decisiva se aproxima, y la humanidad hallará un manantial de
	palabras en la piedra.
</p>

<h3>La primera revolución de la forma: la invención de la escritura</h3>

<p>
	Los esfuerzos por superar las limitaciones de la tradición oral impulsaron avances decisivos en
	la forma de los medios. Hacia el 3200 a. C., los sumerios de la antigua Mesopotamia (actual
	Irak) alcanzaron un hito fundamental con la invención de la escritura. Esta forma temprana,
	conocida como escritura cuneiforme, consistía en marcas en forma de cuña impresas sobre
	tabletas de arcilla (Walker, 1990, 28).
</p>

<p>
	Hacia el 3100 a. C., surgieron los jeroglíficos egipcios como otra de las primeras formas de
	escritura. Junto con la cuneiforme, representan algunos de los ejemplos más tempranos de
	lenguaje escrito y desempeñaron un papel crucial en el registro y transmisión del conocimiento
	y la cultura humanos (Robinson, 2007, 34). Estos sistemas disponían sus signos en secuencias
	lineales, permitiendo leer de izquierda a derecha o de derecha a izquierda, según la
	orientación del texto. Esta innovación estableció una tradición duradera de linealidad textual
	que la literatura heredó y desarrolló como forma principal de narración durante siglos, hasta
	que la literatura digital vino a subvertirla.
</p>

<p>
	En cuanto a los materiales, los egipcios utilizaron principalmente rollos de papiro en lugar
	de tabletas de arcilla, lo que facilitó considerablemente su almacenamiento. Aunque la piedra
	también fue empleada en diversas civilizaciones antiguas, su uso se volvió más prominente en
	contextos monumentales. Inscripciones y estelas en Egipto y Mesopotamia registraron leyes,
	decretos y acontecimientos memorables, siendo la Piedra de Rosetta uno de sus ejemplos más
	notables (Parkinson, 1999, 15).
</p>

<p>
	Se atribuye a los fenicios el desarrollo de uno de los primeros alfabetos hacia el 1050 a. C.
	Su importancia radica en haber reducido el lenguaje a un conjunto limitado de signos
	(alrededor de veintidós caracteres) destinados a representar sonidos consonánticos, lo que lo
	hizo más versátil y accesible que sistemas complejos como la escritura cuneiforme o los
	jeroglíficos (Healey, 1990, 55). La simplicidad y eficacia del alfabeto fenicio facilitaron su
	adaptación por otras culturas. Los griegos, por ejemplo, incorporaron signos vocálicos,
	dando lugar al alfabeto griego, del cual derivaría posteriormente el alfabeto latino empleado
	en muchas lenguas modernas (Powell, 1991, 22).
</p>

<p>
	Otra contribución decisiva de los griegos fue el pergamino, que introdujo una nueva forma de
	disposición textual en códices y manuscritos, marcando el nacimiento de los primeros libros
	(Roberts &amp; Skeat, 1987, 43). El códice representó un hito en comodidad y durabilidad, y
	alteró profundamente las prácticas literarias. Su formato lineal sostuvo la hegemonía del
	libro (Green, 1998), hegemonía reforzada más tarde por la imprenta en el siglo XV. Sin
	embargo, ningún medio reina para siempre. Bajo esta evolución de las formas se repite una
	lógica de obsolescencia: la escritura precipitó la decadencia de rapsodas y <em>aoidoi</em>;
	el papiro volvió obsoletas la piedra y la arcilla; el códice desplazó al rollo. Este patrón
	de progreso mediante la sustitución de medios precedentes ha acompañado toda la historia. Y
	sobre el reino del libro de papel comenzará a proyectarse una amenaza nacida del ámbito
	digital.
</p>

<h3>Impactos estéticos de la evolución de la forma</h3>

<p>
	El primer gran impacto fue el tránsito de lo oral a lo escrito. Con la aparición de la
	escritura, las culturas que accedieron a este nuevo medio comenzaron a transcribir sus
	tradiciones orales, marcando hitos decisivos en la historia literaria (Goody, 1987, 78). Entre
	las tradiciones más tempranas se encuentran los poemas épicos de la antigua Mesopotamia, como
	la <em>Epopeya de Gilgamesh</em>, surgida en la civilización sumeria hacia el 2100 a. C.
	(Sandars, 1972, 15). Del mismo modo, la civilización egipcia produjo obras notables como los
	<em>Textos de las Pirámides</em> y el <em>Libro de los Muertos</em>, originados en el período
	del Reino Antiguo (Faulkner, 2008, 25). En el valle del Indo, textos fundacionales como el
	<em>Rigveda</em> y el <em>Mahabharata</em> emergieron durante el período védico (Buitenen,
	1973, 35). Otras obras tempranas de gran relevancia incluyen la <em>Bhagavad Gita</em>, las
	<em>Upanishads</em> y la literatura griega temprana (Gregory, 2005, 45).
</p>

<p>
	La aparición de la escritura amplificó el contenido transmitido y favoreció la emergencia de
	nuevos géneros literarios, como la tragedia griega (Goody, 1987, 78). Asimismo, esta
	transición de la oralidad a la escritura permitió una circulación más amplia de ideas más allá
	de las comunidades locales, fomentando el intercambio cultural y el desarrollo intelectual
	(Smith, 2008, 75). A medida que surgían nuevos campos del saber y proliferaban los géneros,
	su clasificación se volvió una necesidad inmediata. En este contexto de expansión del
	conocimiento, Aristóteles emprendió el primer estudio sistemático de la estética literaria con
	el propósito de catalogar los géneros mediante el análisis de sus formas y contenidos.
</p>

<p>
	Una cuestión estética central atraviesa este proceso de clasificación: la definición de la
	autoría. La aparición de la escritura marcó el surgimiento de la figura más prominente de la
	literatura universal: el escritor. En un inicio, los autores eran llamados poetas, denominación
	que reflejaba la forma de su escritura. Sin embargo, esta categoría pronto resultó insuficiente
	para clasificar el creciente cuerpo de textos. Comenzaron a aparecer obras que no solo
	preservaban narrativas culturales e históricas, sino que también vehiculaban ideas
	científicas, filosóficas, religiosas y éticas. Aristóteles fue uno de los primeros en señalar
	las limitaciones de definir lo literario exclusivamente por la forma. En la
	<em>Poética</em>, observa: “Aunque un tratado de medicina o de física se exponga en verso, se
	acostumbra llamar poeta a su autor; y, sin embargo, Homero y Empédocles no tienen en común
	más que el metro, de modo que sería justo llamar al uno poeta y al otro físico antes que
	poeta” (Aristóteles, Butcher, 1922, Libro I, 1447b).
</p>

<p>
	Este proceso de clasificación desplazó el foco hacia el contenido y con ello propició una
	segregación del saber. La sabiduría colectiva, antes integrada en la literatura, comenzó a
	diferenciarse en campos específicos. En algunos casos, como las ciencias, esta separación fue
	casi completa; en otros, como la filosofía, los elementos literarios siguieron ejerciendo una
	influencia notable. Platón, por ejemplo, puede leerse tanto como escritor como filósofo. Este
	proceso de segregación del conocimiento alcanzó su culminación en la Ilustración, ejemplificado
	en la célebre división de Christian Wolff entre <em>Geisteswissenschaften</em> (ciencias del
	espíritu) y <em>Naturwissenschaften</em> (ciencias naturales). Durante siglos, ambas ramas
	evolucionaron por caminos paralelos. Sin embargo, las tecnologías digitales han abierto nuevas
	posibilidades de integración y trabajo interdisciplinario, convirtiendo la interdisciplinariedad
	en uno de los avances más significativos propiciados por los formatos digitales.
</p>

<p>
	Otro impacto estético crucial de la revolución de la escritura fue la migración de la
	literatura al libro, proceso que la confinó progresivamente al ámbito de lo escrito. En este
	tránsito, la literatura perdió gran parte de su dimensión multimodal. En la épica temprana,
	el poeta actuaba acompañado de música y danza, involucrando múltiples sentidos para cautivar a
	la audiencia. En la tragedia, primer género codificado por escrito, este elemento performativo
	aún permanecía y movilizaba diversos sentidos del espectador. Pero a medida que la literatura
	se replegó sobre el libro, esta multimodalidad se redujo, estrechando la experiencia
	literaria al acto de la lectura.
</p>

<p>
	Estos núcleos estéticos están sujetos a la evolución de la forma. Como veremos, los formatos
	digitales revolucionarán cada uno de ellos, dando lugar a nuevos géneros literarios y
	cuestionando las nociones tradicionales de autoría. Asimismo, facilitarán la integración del
	conocimiento y el trabajo interdisciplinario. Finalmente, restaurarán la multimodalidad y
	elevarán la participación del usuario y la experiencia estética a niveles de riqueza sin
	precedentes.
</p>

                
