				<h3>Nodo 1.2</h3>

				<p>
					Ya han pasado varios días y, poco a poco, me voy procurando comida y una morada decente.
					Siguiendo la orientación del sol, sé que me encuentro hacia el occidente. Al oriente se
					extienden los palmerales donde desapareció aquel “Hombre Palmera”. Yo decidí tomar la
					dirección contraria por temor a reencontrarmelo. Además, me atrajo una vegetación frondosa
					que parecía ofrecer un buen resguardo. Debo confesar que, desde aquella tarde, un
					cosquilleo paralizante me recorre el estómago: siento miedo y desamparo en este lugar.
				</p>

				<p>
					Existen algunos árboles frutales que jamás había visto. En especial, he reparado en unos
					frutos salados y de color fluorescente, que sacian mi apetito desde que los encontré.
					Estas plantas también poseen flores de pétalos blancos, del tamaño de mi mano, que he
					utilizado para improvisar mi lecho. Aunque he viajado por muchos lugares biodiversos,
					jamás me había topado con un tipo de vegetación tan novedosa. Siempre me ha fascinado
					descubrir nuevos parajes en el mundo; en otro contexto, esta experiencia sería un logro
					único. Sin embargo, hay algo que me impide conectarme del todo con lo que está sucediendo.
					Aquí, por primera vez, me incomoda la soledad.
				</p>

				<p>
					Hoy me he despertado con un firme propósito: explorar. A pesar de la incertidumbre, debo
					admitir que este lugar no me resulta del todo inhóspito. Sin embargo, pasar tantos días en
					el mismo sitio, aun cuando duermo sobre un mullido lecho de flores, me causa náuseas.
					También los atardeceres empiezan a volverse monótonos. Esto me resulta completamente
					inaceptable. Por ello, hoy buscaré un cambio de aires.
				</p>

				<p>
					Con bejucos he tejido una cesta donde guardo varios frutos y suficientes pétalos para
					disponer de un lugar donde reposar al caer la noche. Desde la copa de un árbol, hacia el
					suroccidente, entre sombras de una colina, vislumbro una explanada que tiene el
					inconfundible aspecto de un campo arado. La perfecta disposición de los surcos me hace
					pensar que ahí ha habido intervención humana, lo cual me hace dudar, pues en estas
					circunstancias podría ser un arma de doble filo. Emprendo mi marcha, ya que la lejanía del
					camino me indica que tendré varios días para meditarlo.
				</p>

				<p>
					En efecto, he contado al menos una decena de atardeceres antes de dejar atrás la
					vegetación frondosa. El reflejo cegador del sol me obliga a buscar un refugio transitorio.
					Me dirijo hacia un conjunto de monolitos que me recuerda los parajes de Stonehenge, salvo
					que estos están incrustados en la ladera de una colina. Creo que encontraré sombra tras
					esas piedras.
				</p>

				<p>[Desplegar imagen 360° del panorama]</p>

				<p>
					Recostado en la base, siento la frescura de un peñón inmenso; sin embargo, de él emana una
					fetidez milenaria que me provoca náuseas. Suelto la cesta para aligerar la carga y
					refresco cada una de mis extremidades, apoyándolas de manera alternada sobre la superficie
					áspera y húmeda, sin dejar de cubrirme la nariz. Nauseabundo, reflexiono en lo poco que me
					queda para coronar la cumbre y llegar finalmente a mi destino.
				</p>

				<p>
					De pronto, un sonido crujiente tras la roca me pone en alerta, pero ya es demasiado tarde
					para reaccionar: una rama repleta de hojas amargas me amordaza y el paisaje se va
					disipando en una nube cargada de sopor.
				</p>

