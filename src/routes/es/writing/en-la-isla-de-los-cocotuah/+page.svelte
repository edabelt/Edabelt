				<h3>Nodo 2.1</h3>

				<p>—Vahlia: ¿Quién eres?</p>

				<p>
					Mi nombre es Yuuban Yataque, que significa “Tierra Viva” en mi lengua materna. Pertenezco
					a la tribu amazónica de los Yanihuír.
				</p>

				<p>
					—Vahlia: Viniendo de tan lejos, ¿algo muy importante estarás buscando en estas tierras?
				</p>

				<p>
					—Yuuban: La verdad es que lo único que hago es buscar atardeceres originales, para
					encontrar en los amaneceres algún “berenjenal” que le dé sentido a mi vida.
				</p>

				<p>—Vahlia: ¡Pues pocos atardeceres te quedan si no te tomas en serio mi interrogatorio!</p>

				<p>—Yuuban: Y lo hago. Te digo que voy por el mundo coleccionando atardeceres.</p>

				<p>—Vahlia: Dime, pues, ¿qué tipo de atardecer viniste buscando a este lugar?</p>

				<p>
					—Yuuban: No lo sé, de veras. Solo recuerdo haber presenciado el eclipse fotogradual en
					algún recóndito lugar del hemisferio norte y, sin saber cómo, aparecí en este sitio, donde
					la monotonía de los ocasos entristece mis noches, aunque duermo en un lecho de pétalos
					blancos.
				</p>

				<p>
					—Vahlia: Hum, algo de verdad hay en tus palabras, pero no soporto tu falta de rigor. ¿Qué
					tal si te ayudo a precisar las respuestas? Me refiero a: ¿qué buscabas en esta parte de la
					isla?
				</p>

				<p>
					—Yuuban: Confundes mi desconocimiento con falta de rigor. Para empezar, ni siquiera estaba
					seguro de que esto fuera una isla. Solo lo intuía porque no había conocido a nadie más que
					al “Hombre Palmera” y no he probado más alimento que frutos salados. En una ocasión
					vislumbré un campo arado, con surcos perfectamente dispuestos, detrás de una colina llena
					de piedras monolíticas. Me dirigí hacia allí con la esperanza de hallar presencia humana.
					¡Y, mira, la encontré! Aquí me tienes, despertando atado a este árbol, en otro fastuoso
					amanecer de los que la mano humana siempre me propina.
				</p>

				<p>
					—Vahlia: Déjame organizar un poco tus ideas. Primero: no es un “Hombre Palmera”, sino un
					miembro de la tribu Cocotuah. Segundo: los frutos no son salados, eres tú quien presenta
					síntomas de distorsión del gusto.
				</p>

				<p>
					—Yuuban: Espera, espera, esper… No te puedo entender si haces razonamientos tan largos…
				</p>

				<p>—Vahlia: ¡Y menos me entenderás si me interrumpes cuando hablo!</p>

				<p>
					Tercero: no se trata de ningún “arado” sino de mi semanario. Cuarto: a lo que llamas
					“piedras monolíticas” son, en realidad, pilas de excremento de escarabajos. Quinto:
					estamos lejos del amanecer. Y, para concluir, no estás atado a ningún árbol: te he
					envuelto entre cortezas y raíces curativas para paliar tus síntomas.
				</p>

				<p>
					—Yuuban: Siento interrumpirte. Es solo que, salvo lo de los excrementos, no he entendido
					nada de lo que me dices. ¿Qué te parece si primero me explicas a qué distorsión del gusto
					te refieres?
				</p>

				<p>
					—Vahlia: ¿Echt? Eso no era lo primero, sino lo segundo. Con semejante falta de rigor, no
					entiendo cómo es que hablas tan bien alemán.
				</p>

				<p>
					—Yuuban: De cualquier manera, me gustaría que me aclares por qué dices todo esto. ¿A qué
					te dedicas? ¿Qué es ese semanario? ¿De qué síntomas hablas?
				</p>

				<p>
					—Vahlia: Mira, he venido a esta isla porque aquí habita una población no contactada.
					Practican una medicina ancestral que es la única esperanza contra uno de los grandes males
					que azota al planeta. Debo obtener esa medicina; sin embargo, el tiempo se agota.
				</p>

				<p>—Yuuban: ¿Tiempo para qué?</p>

				<p>
					—Vahlia (entre sollozos): Para evacuar a la población nativa. Siempre recogí mis hallazgos
					en un diario, pero lo perdí cuando un gran oleaje —el mismo que te trajo a esta isla—
					borró todo lo que tenía escrito en la arena. La llegada de esos torrentes helados me
					demostró que ya es demasiado tarde: se ha iniciado el deshielo de los glaciares sagrados.
					Lo único que puedo hacer es dejar vestigios sólidos de que aquí hubo supervivientes.
					Entonces, busqué la explanada resguardada por la colina y por la fetidez de los
					excrementos de insectos. Allí sembré con palmeras los acontecimientos que han acaecido
					después del eclipse solar fotogradual. Las labores de siembra son tan arduas que me
					impiden llevar un diario al uso, por eso decidí “sembrar” las líneas de un semanario.
				</p>

				<p>
					—Yuuban (con tono sarcástico): ¡Ufff! Todo esto que cuentas me llena de temor y
					desconcierto. ¿Moriremos ahogados en esta isla?
				</p>

				<p>
					—Vahlia: Es muy probable. Pero, si me ayudas a ejecutar mi plan de escape, al menos podré
					llevar conmigo el remedio sagrado.
				</p>

				<p>
					—Yuuban: A estas alturas, sé que preguntarte más solo me confundirá más todavía. Además,
					soy torpe para interrogar porque casi nunca tengo a alguien cerca para hacerlo. Me
					interesan más los hechos y la aventura. Dime, pues, ¿qué debo hacer?
				</p>

				<p>
					—Vahlia: Deberás infiltrarte en la tribu de los Cocotuah. Solo podrás lograrlo si sigues
					mis indicaciones al pie de la letra.
				</p>

				<p>—Yuuban: ¿Y si tú eres la rigurosa, por qué no lo has hecho tú misma?</p>

				<p>—Vahlia: La verdad, soy incapaz de bailar.</p>

				<p>—Yuuban (con ironía): Me ha quedado claro. Déjame marchar, entonces.</p>

				<p>—Vahlia: No tengo más opción que hacerlo. Espero no haber caído en un engaño tuyo.</p>

				<p>
					—Yuuban: Engañar no es lo mío; son las invasiones ajenas las que me obligan a ser lo que
					no pretendo. Yo solo amo mi libertad. Adiós, rubia sin nombre.
				</p>

				<p>—Vahlia (ríe): Me llamo Vahlia Rigursson, y pertenezco a los pueblos del norte.</p>

				<p>
					—Yuuban: Conozco algunos de esos pueblos y los admiro, pero mis raíces están sembradas muy
					al sur.
				</p>

				<p>
					—Vahlia: Antes de partir, toma un poco de este brebaje que he logrado elaborar. No es un
					remedio, pero te servirá como paliativo cuando los síntomas se intensifiquen. El antídoto
					solo puede extraerse del sagrado coco gigante. Por eso debes ir a buscarlo.
				</p>

				<p>—Yuuban: Espera... ¿De qué síntomas estás hablando?</p>

				<p>—Vahlia: Padeces una gran enfermedad.</p>

				<p>—Yuuban: Ja, ja. Sin duda sufro de hastío ante los ocasos monótonos.</p>

				<p>
					—Vahlia: No es eso lo que debe preocuparte. Aquí los verás cada vez más de cerca: el Sol
					se está convirtiendo en una supergigante roja.
				</p>

				<p>—Yuuban: Ah, bueno... Entonces, ¿de qué debería inquietarme?</p>

				<p>—Vahlia: Yuuban, de la tribu de los Yanihuír... tienes la peste.</p>

				<ul>
					<li>
						Yuban, una apasionante aventura te espera si decides ayudar a Vahlia en su plan de
						huída. Nodo 2.1.1
					</li>
					<li>
						Algo te dice que Vahlia a perdido la cabeza y debes continuar tu camino obviando todo lo
						que te dijo. Nodo 2.1.2
					</li>
					<li>Acompaña a Vahlia a ejecutar su plan de escape. Nodo 2.3</li>
				</ul>

				<h3>Nodo 2.1.1</h3>

				<p>
					Todavía no estoy completamente integrado en esta tribu, pero ya tengo un nombre y, lo que
					es más importante, muchos amigos. De haber sabido la hospitalidad de este pueblo, no
					habría dudado en seguir al “Hombre Palmera”. Sin embargo, lo esencial es que estoy aquí y,
					para ser sincero, me siento feliz.
				</p>

				<p>
					Vivo en una enorme vivienda con paredes de madera de palma, techos de hojas de palma y
					pisos de corteza de palma, igual que todos los habitantes de la aldea, porque todos
					compartimos la misma casa.
				</p>

				<p>
					Aun tengo problemas para comunicarme, pero gracias a la guía de mi gran amigo “Dos
					Palmas”, voy aprendiendo poco a poco la dinámica de su lenguaje. Después de todo, el
					“Hombre Palmera” no era ningún sordomudo; simplemente, esta tribu se comunica mediante
					gestos y lenguaje corporal. Lo llamo con dos palmadas y añado una tercera si es urgente.
					Para saludarnos, juntamos las palmas y las giramos a la derecha si es de día, y a la
					izquierda si es de noche. Para despedirnos, frotamos el dorso de nuestras manos. Cuando
					estoy feliz, doy dos giros; si estoy triste, dibujo un círculo con mi barbilla que cierro
					a la altura del pecho.
				</p>

				<p>
					Al despertar, todos nos reunimos en perfecta sincronía, chocamos nuestras palmas y
					celebramos la llegada de un nuevo día. Después, cada quien se dedica a sus tareas
					domésticas, que se hacen de manera rotativa. Al caer la tarde, nos congregamos alrededor
					de una hoguera hecha de rastrojos y disfrutamos de un gran banquete de filetes de coco.
					Los niños se acurrucan en los regazos de sus seres queridos, mientras los ancianos
					ilustran historias increíbles, cuyo significado aún no comprendo del todo, pero me fascina
					la magia de sus danzas y la armonía de cada movimiento. Sin embargo, todo se detiene en
					este momento: debemos permanecer bajo techo, pues la cosecha está muy cerca.
				</p>

				<p>
					Durante la cosecha, el cielo se desgarra en aguaceros torrenciales y el viento furioso
					sacude las palmeras, obligando a la gente a refugiarse en nuestro gran albergue hasta que
					cese la tormenta de enormes cocos que caen como granizo. Una vez en tierra firme, se
					recogen los frutos, y la pulpa del coco se conserva para preparar alimentos, mientras que
					el agua se almacena en enormes barriles de madera de palma que se entierran durante dos
					meses. De ahí surge una bebida fermentada que alegra a quien la consume y lo impulsa a
					ejecutar movimientos celestiales en honor a la naturaleza. Mi amigo “Dos Palmas”, que la
					bebe a diario, me cuenta que existen civilizaciones alienígenas con danzas tan
					sofisticadas que, al formar enormes círculos, giran como ruedas espaciales para recorrer
					distancias inimaginables entre mundos.
				</p>

				<p>
					Una vez, completamente embriagado por el brebaje, “Dos Palmas” me reveló un secreto. Él
					levantó su brazo lánguido y señaló unas dunas que se extendían hacia el oriente de la
					isla. Luego, señaló el cuenco de coco en el que bebía y trazó una gran elipse con los
					brazos. Escarbó en la arena un hueco de unos cincuenta centímetros de diámetro y completó
					su elipse imaginaria con aquellos brazos larguísimos. Sin duda, me estaba mostrando el
					camino hacia donde se hallaba oculto el sagrado coco gigante.
				</p>

				<p>
					La revelación me cayó como un plomo y me recordó la verdadera razón por la que había
					llegado a esta tribu. Esa noche no concilié el sueño. Entre lágrimas, me sentía un
					traidor, un verdugo parecido a esos que tanto criticaba. Y, por primera vez en mucho
					tiempo, volví a pronunciar palabras, balbuceando un interrogante que me acechaba:
				</p>

				<p>
					—¿Qué tal si todo es cierto? Quizá tengas razón, Vahlia... Vahlia de los pueblos del
					norte.
				</p>

				<ul>
					<li>
						¿Crees que merece la pena ir a confesar el secreto a Vahlia para ayudarla en su misión
						de encontrar el antídoto a la peste? Encuentro con Vahlia Nodo 2.1.1.1
					</li>
					<li>¿Deseas conocer tu desenlace en la tribu despues de la traición? Nodo 2.1.1.2</li>
					<li>
						Consideras una traición revelar el secreto y decides permanecer en la tribu. Nodo 2.1.2
					</li>
				</ul>

				<h3>Nodo 2.1.1.2</h3>

				<p>
					Han pasado más de un par de cosechas desde mi último encuentro con Vahlia. A veces me
					siento un traidor, pero… ¿traidor de qué? Al fin y al cabo, no creo que Vahlia hiciera
					algo con la información que le di. Además, si todo es como ella dice, de su éxito depende
					la salvación de muchas personas. En todo caso, estos remordimientos se desvanecen cuando
					me sumerjo en las labores colectivas.
				</p>

				<p>
					Ahora comprendo mucho mejor el lenguaje corporal y participo, como cualquier otro miembro,
					en todas las actividades de la tribu. Incluso entiendo el humor y me atrevo a contar
					algunos chistes con danzas ridículas. No he olvidado las palabras, pero tampoco las
					extraño.
				</p>

				<p>
					He perfeccionado algunas técnicas de tejido de palma para confeccionar prendas y atuendos
					para cada integrante. Además, he aprendido a percibir los colores nuevos que el Sol va
					mostrando con su gigantismo, y aplico combinaciones exóticas en mis tejidos. En este
					momento, estoy ocupado preparando el atuendo para mi coreografía de consagración, que debo
					presentar ante todos durante la gran celebración.
				</p>

				<p>
					Al llegar la sexta cosecha, los miembros ya están aptos para la ceremonia de consagración
					a la tribu. Por primera vez, podré liderar las danzas en los encuentros nocturnos. También
					me entusiasma probar, por primera vez, la bebida de la alegría y descubrir las danzas
					siderales de las que habla “Dos Palmas”.
				</p>

				<p>
					Para mi presentación, he elegido a “Yemas Ligadas” como compañera de baile porque me gustó
					su nombre. Para representarlo, unimos las yemas de todos los dedos y después doblamos
					lentamente las falanges de los índices hasta que las uñas se junten. Ya tenemos casi todo
					listo: hoy hicimos el último ensayo con los atuendos que llevaremos mañana en la
					ceremonia.
				</p>

				<p>
					Finalmente ha llegado el gran día. Me encuentro en ayunas con los ancianos, llevando a
					cabo la última meditación antes de iniciar las danzas de consagración para la tribu… mi
					tribu. El vacío de mi mente se interrumpe al percibir la presencia de mi compañera: podría
					sentirla y bailar con ella aunque estuviera a kilómetros de distancia. El murmullo de la
					procesión se acerca. El recinto se llena de sahumerios. Y las manos de mi compañera se
					aferran a las mías: ha llegado el momento de ofrendar a la tribu nuestra danza de
					consagración.
				</p>

				<p>
					De pronto, nuestra danza se ve interrumpida por un canto inefable que proviene del
					occidente. Todos reaccionamos con desconcierto, chocamos unos contra otros y tapamos
					nuestros oídos ante esa música, que resulta abrumadora para la mayoría. Algunos corremos
					hacia las playas de los frutales frondosos, mientras el canto se intensifica más y más. Al
					llegar al final de los palmerales, veo por primera vez a toda mi tribu fundirse en gritos
					y llantos.
				</p>

				<p>
					Desde los árboles de frutos fluorescentes, aparece un trineo reconvertido en triciclo
					gigante, con tres aros de coco descomunal como ruedas. En el centro, una mujer acciona,
					con empoderado pedaleo, un sistema de poleas, y en la parte trasera del carruaje reposa el
					sagrado coco gigante.
				</p>

				<p>
					Al llegar a la playa, una manada de cetáceos, aparejada con bejucos, entona los cantos
					inefables de la partida. La auriga toma las riendas y, sin dejar de agitarlas, avanza mar
					adentro. Su cabellera dorada ondea sobre las olas, como si fuera el mismísimo Helios
					conduciendo su carro, o un Prometeo tras robar el fuego a los dioses. Adiós, Vahlia de los
					pueblos del norte.
				</p>

				<p>La escena sublime se quiebra con la carcajada de un espectador inesperado.</p>

				<p>
					—¿Así que también has venido por aquí a propagar la peste? Con estos calores infernales,
					más te vale enseñarme a sudar frío si quieres volver a escapar vivo.
				</p>

				<p>Y, entonces, sucumbo apercollado por la mano apabullante de Ruslan.</p>
