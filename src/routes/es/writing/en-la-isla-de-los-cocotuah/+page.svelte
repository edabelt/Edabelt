				<h2>En la isla de los Cocotuah</h2>

				<p><strong>Elije y renombra a tu Personaje:</strong></p>

				<ul>
					<li>Nodo 1 [Yuuban Yataque]</li>
					<li>Nodo 2 [Vahlia Rigursson]</li>
				</ul>

				<h3>Nodo 1</h3>

				<p>
					Una gran fascinación por el crepúsculo me ha llevado a convertirme en lo que aspiro a ser:
					un coleccionista de atardeceres. Cada ocaso es, para mí, algo más que un espectáculo
					visual; encierra un compendio de significados. Simboliza la satisfacción de una jornada
					vivida, pero también el peso del cansancio acumulado que me obliga a claudicar cada noche,
					tal como el dios Ra sucumbe engañosamente ante la penumbra. He presenciado cómo se
					desmorona en pedazos sobre las arenas infinitas del desierto de Atacama y cómo se despeña
					en torrentes por las cataratas del Niágara. Lo he visto escalar, imponente, el Aconcagua,
					solo para deslizarse vertiginosamente por su ladera y desaparecer en la bruma de la sima.
					Incluso, he aguardado, en vano, a que se oculte tras sus danzas boreales en Escandinavia,
					y también he llorado durante meses su ausencia gélida desde cualquier mirador de Nunavut.
				</p>

				<p>
					Pero sé que renacerá, trayendo consigo un nuevo día y, con él, el eterno interrogante que
					me acecha: ¿Qué haré hoy con mi vida?
				</p>

				<p>
					Esa condición hace que rara vez tenga despertares parecidos. La razón es muy sencilla:
					nunca duermo en el mismo sitio. En consecuencia, estoy expuesto a los más terroríficos
					amaneceres. No me refiero a enfrentar las adversidades de los climas extremos en las
					madrugadas, que ciertamente no son agradables, sino a las peripecias que surgen cuando los
					locales descubren a un intruso acampando en su territorio.
				</p>

				<p>
					Las anécdotas son innumerables. Basta con relatar cómo fui arrastrado nieve abajo, atado a
					un trineo de esquimales escandinavos, quienes creían que mi elevada temperatura corporal
					era la causa del deshielo que, desde hacía ya algún tiempo, sufrían los glaciares
					sagrados.
				</p>

				<p>
					Me llevaron con su líder, Russlan, un mastodonte de más de dos metros de estatura que
					llevaba un sombrero con cuernos de reno. Al parecer, no conocía otra forma de comunicación
					más que los gritos. Hablaba una lengua de raíces protogermánicas, la cual nos permitió
					mantener una conversación algo trabada.
				</p>

				<p>
					Le expliqué que estaba por esas tierras con el fin de contemplar el eclipse solar
					fotogradual. Por primera vez desde que se lleva registro, el Sol, Mercurio, Marte, Venus y
					la Luna se alinearían, sumiendo al Sol en una gradación de capas oscuras, cada vez más
					claras, a medida que cada astro se fuera desalineando. El fenómeno natural había causado
					mucho revuelo entre los aficionados, así que yo me procuré un buen lugar para
					presenciarlo.
				</p>

				<p>
					Dado que, bien arriba en el hemisferio norte, por esas épocas del año el atardecer se
					prolonga, tenía la intuición equivocada de que dispondría de más horas de eclipse. Pero
					mis esfuerzos por explicárselo fueron en vano, en parte porque él entendía el alemán a
					medias y, en mayor parte, porque no dejaba de tocarme por todas partes, extrañado por mi
					alta temperatura corporal.
				</p>

				<p>
					Le convencí de que la fiebre era un gran paliativo para caldear sus cuerpos frente a la
					gelidez ártica. Rápidamente, todos contrajeron el “remedio”. Huí, pues, entre sus sollozos
					febriles e impotencia, ya que el sofoco de las flemas les impidió perseguirme.
				</p>

				<p>
					Esta vez, un golpe seco impactó sobre mi rostro, imprimiendo un dolor que se propagó de
					arriba a abajo por mi cuerpo, se detuvo en mis sienes y, finalmente, se precipitó en un
					par de lágrimas desde mis ojos. No es el malestar de la coz lo que me inquieta, sino el
					desconcierto; lo ilógico del recurso. Quien me golpeó quería despertarme, pero la
					hinchazón me impide abrir los ojos. El haz de luz que se cuela entre mis párpados anuncia
					otro duro amanecer. Ya he aprendido que a los malos días también hay que ponerles mala
					cara. Así que lo afronto con los pómulos izados, el entrecejo bien fruncido y los labios
					apretados, como la sonrisa triste de un payaso.
				</p>

				<p>
					El individuo tiró de mi cabello húmedo, me arrastró entre la resaca y me arrojó sobre las
					dunas, rebozado enteramente de arena cálida. A pesar de su introducción abrupta, resulta
					ser un personaje amistoso, incluso algo cómico. Aún no me ha explicado por qué me despertó
					de esa manera, ni yo se lo he preguntado; mi mente está ocupada intentando recordar qué
					clase de atardecer me ha traído hasta aquí. Tampoco entiendo por qué sacude mi brazo y
					rasca con sus pies en la arena, como indicando que lo siga. No entiendo su mensaje. Le
					pregunto si acaso es mudo, pero toda palabra es un esfuerzo vano, y me invade la leve
					sospecha de que también podría ser sordo.
				</p>

				<p>
					Me apoyo en su mano para incorporarme. Una extraña mezcla de fortaleza y fragilidad emana
					de ella: su dorso es tosco y peludo, de un color oscuro como concha de coco viejo,
					mientras que su palma es blanquecina y delicada, casi húmeda, como la pulpa de coco
					fresco. Deslizo la mirada sobre su brazo, reparando en su languidez, casi elástica; se
					elonga lo suficiente para sostener mi peso. Mi desconcierto se intensifica al seguir la
					línea de su silueta: un tronco erguido, coronado por un matorral de pelo desproporcionado
					que parece capaz de dar sombra a varios cuerpos como el suyo. Entonces, una revelación me
					atraviesa como un destello: lo llamaré el “Hombre Palmera”.
				</p>

				<p>
					Parece que no le agrada mi actitud. Suelta mi brazo abruptamente e inicia una coreografía
					con movimientos gelatinosos y un rostro rígido, que imprime mucha seriedad a un mensaje
					que sigo sin descifrar. Finaliza su exhibición y se aleja, señalando sus huellas,
					desdibujadas rápidamente por un sin fin de granos nuevos traídos por el vaivén del viento.
				</p>

				<p>
					Este lugar se caracteriza por su infinita extensión de arena, apenas interrumpida por
					imponentes palmeras que brotan de las profundidades. Son tan altas que no alcanzo a ver
					qué frutos llevan. Aunque ya vislumbro cómo el sol se humedece levemente en los confines
					del océano, sus rayos aún recaen espesos sobre el paraje, irradiando espectros
					indescifrables. A lo lejos, en esa amalgama de tonalidades arcanas, la figura del “Hombre
					Palmera” se desvanece.
				</p>

				<p>
					El silencio de su ausencia se confunde entre el regurgitar de espuma marina sobre las
					playas y el silbido del viento agorero. Sin más director que el destino, se interpreta la
					misma sinfonía lúgubre que parece orquestada solo para mí. Una vez más, como siempre,
					aquí, en el instante mismo en que mi existencia se hace sórdida ante la agonía de la
					lumbre, vuelvo a ser el único espectador en el concierto inefable de mi soledad.
				</p>

				<ul>
