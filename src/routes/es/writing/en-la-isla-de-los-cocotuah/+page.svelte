				<h3>Nodo 2 [Vahlia]</h3>

				<p><strong>Semanario de Vahlia</strong></p>

				<p><strong>Una semana después del eclipse fotogradual</strong></p>

				<p>
					Seguido al extraño fenómeno solar ocurrido hace unos días, grandes oleajes han sacudido
					esta isla. No son tan imponentes como los tsunamis que afectan al trópico y al hemisferio
					sur del planeta, sino más bien maretazos: olas no muy elevadas, pero sí muy prolongadas.
				</p>

				<p>
					Tras tomar muestras en varios puntos, se aprecia una disminución significativa en la
					temperatura del agua. También destaca su pureza y transparencia. Parecería apresurado
					sacar conclusiones de estas variables; sin embargo, un par de hallazgos han resultado
					reveladores.
				</p>

				<p>
					El primero consiste en un trineo —utilizado solo por los esquimales que habitan la zona
					polar ártica— que apareció encallado entre la arena y la resaca. El segundo se refiere a
					los cantos de ballenas polares. Todo ello sustenta la hipótesis de que se ha desencadenado
					el fenómeno que tanto se temía: el deshielo de los glaciares sagrados es ya irreversible.
				</p>

				<p>
					<em>
						Nota personal: Estos cetáceos son seres inteligentísimos y extraordinarios. No me da
						miedo estar sola, pero echaba de menos algún amigo.
					</em>
				</p>

				<p><strong>Segunda semana después del eclipse fotogradual</strong></p>

				<p>
					Después de varios cálculos tangenciales de la circunferencia solar con la línea del
					horizonte, ha quedado demostrado lo que ya se intuía a simple vista: el Sol ha
					incrementado su radio en aproximadamente un tercio. Esto seguramente esté asociado al
					deshielo. No obstante, por más fuerza intuitiva que tenga esta hipótesis, de momento solo
					es una conjetura, ya que no disponemos de pruebas científicas para fundamentar la
					correlación.
				</p>

				<p>
					Por otra parte, la temperatura de las profundidades terrestres también se ha incrementado.
					El proceso de fermentación siempre había durado, al menos, dos meses desde que el brebaje
					se entierra. Sin embargo, ayer un chorro de líquido emergió a la superficie. Hoy he
					desenterrado la barrica y la bebida está completamente fermentada y apta para el consumo,
					con casi la mitad del tiempo habitual. Tal catalización solo puede explicarse por un
					aumento de la temperatura en el subsuelo.
				</p>

				<p>Esta tarde me espera un gran brindis.</p>

				<p><strong>Tercera semana después del eclipse fotogradual</strong></p>

				<p>
					Tras algunos días de cuidado del cuerpo y de labores en el arado, retomé la exploración.
					Me dirigí hacia el oriente de la isla, cerca de la costa donde está encallado el trineo.
					Se halla justo en la zona donde comienza la vegetación y lo suficientemente cubierto de
					arena para no ser visible a simple vista, lo que, por otro lado, me obliga a dedicar un
					buen tiempo a desenterrarlo.
				</p>

				<p>
					Mientras lo intentaba, me distrajo la aparición de un nativo de la tribu Cocotuah. Llevaba
					a rastras, por el cabello, a otro individuo. Pensé que este segundo podría estar
					relacionado con la llegada del trineo; sin embargo, sus facciones distaban de ser
					nórdicas. Más bien, poseía rasgos indígenas: cabellera larga y lacia, y un tono tostado de
					piel típico de la gente del trópico. Me camuflé trepando a la copa de un árbol hasta ver
					cómo se desarrollaba la escena. Sin duda, debo seguirle el rastro a ese individuo.
				</p>

				<p><strong>Quinta semana después del eclipse fotogradual</strong></p>

				<p>
					Han sido un par de semanas laboriosas. No ha sido complicado seguirle la pista al
					indígena. Ha establecido su campamento en el occidente de la isla, justo en medio del
					bosque de frutos fluorescentes. Al parecer, tiene un gran apetito, pues en aproximadamente
					cien metros cuadrados alrededor de su campamento, los árboles han sido despojados de
					flores y frutos. Precisamente, ese boquete en los helechos florales fue la pista
					fundamental para ubicarlo. Afortunadamente, se encuentra lo bastante lejos como para no
					interferir en mis labores.
				</p>

				<p>
					Lo que sí me ha llevado más tiempo de lo esperado es transportar el trineo hasta mi
					campamento. Por suerte, descubrí en él una multitud de objetos de valor incalculable.
					Entre ellos, destaca un hacha segur, con un mango tallado en madera de alerce siberiano,
					además de varios instrumentos de navegación. Lo más valioso es un mapa, grabado en piel de
					oso polar, que señala el camino conducente a los glaciares sagrados. Está escrito en un
					dialecto protogermánico muy antiguo, el mismo que dio origen a mi lengua materna.
				</p>

				<p>
					Ya cuento con lo necesario para ejecutar un plan de huida de la isla antes de que se
					intensifiquen los efectos del deshielo. El primer paso consistió en desarmar el trineo por
					partes y llevarlo hasta un escondite seguro. Luego quería trabajar en el sistema de poleas
					para su propulsión, así que me dirigía a los arenales para trazar mejor los cálculos. Sin
					embargo, un suceso inesperado me detuvo: el indígena ha abandonado su campamento. Por lo
					tanto, ahora dudo si iniciar mañana mismo su rastreo o retomar el diseño del sistema de
					poleas.
				</p>

